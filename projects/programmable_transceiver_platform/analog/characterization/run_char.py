def evidence_current(path):
    """Recompute the source/generated hashes recorded in an evidence JSON."""
    d = json.loads(Path(path).read_text())
    base = Path(path).parent
    out = {}
    for group in ('source_hashes', 'generated_hashes'):
        for k, v in (d.get(group) or {}).items():
            cands = [base / k, base.parent / k, base / Path(k).name]
            f = next((c for c in cands if c.exists()), None)
            out[k] = 'missing' if f is None else ('current' if sha(f) == v else 'stale')
    return out


def abstracts():
    res = {}
    for name, ref in REFERENCED.items():
        work = SCRATCH / 'abstracts' / name
        if work.exists():
            shutil.rmtree(work)
        work.mkdir(parents=True)
        shutil.copy(ref['gds'], work / 'in.gds')
        (work / 'abs.tcl').write_text(ABSTRACT_TCL.format(gds='in.gds'))
        r = ck.docker(ck.DIGITAL_IMAGE, work, f'magic -dnull -noconsole -rcfile {ck.PDK}/libs.tech/magic/gf180mcuD.magicrc /work/abs.tcl')
        (work / 'abs.log').write_text(r.stdout + r.stderr)
        tops = [t for t in ((work / 'tops.txt').read_text().split() if (work / 'tops.txt').exists() else []) if t != '(UNNAMED)']
        lefs = []
        for t in tops:
            if (work / f'{t}.lef').exists():
                shutil.copy(work / f'{t}.lef', GEN / f'{name}.lef')
                lefs.append(t)
        hashes = evidence_current(ref['evidence'])
        res[name] = dict(owner=ref['owner'], access=ref['access'], gds=str(ref['gds'].relative_to(ROOT)),
                         gds_sha256=sha(ref['gds']), top_cells=tops, lef=f'generated/{name}.lef' if lefs else None,
                         evidence=str(ref['evidence'].relative_to(ROOT)), evidence_hashes=hashes,
                         evidence_stale=[k for k, v in hashes.items() if v != 'current'])
    (GEN / 'referenced-structures.json').write_text(json.dumps(res, indent=1) + '\n')
    return res


# ------------------------------------------------------------------ benches
def stage_atb(work):
    work.mkdir(parents=True, exist_ok=True)
    ATB_DIR.mkdir(parents=True, exist_ok=True)
    for cell in ('atb_leaf_f', 'atb_leaf_s', 'atb_grp', 'atb_pad'):
        dst = ATB_DIR / f'{cell}.pex.spice'
        if not dst.exists():
            shutil.copy(ATB_SRC / cell / f'{cell}.pex.spice', dst)
        txt = dst.read_text().replace(f'{cell}_flat', cell)
        (work / f'{cell}.pex.spice').write_text(txt)
    if (GEN / 'char_atb.ext.spice').exists():
        shutil.copy(GEN / 'char_atb.ext.spice', work / 'char_atb.ext.spice')


def header(corner, temp):
    return f'* {corner} {temp}C\n' + ck.models(corner) + f'.temp {temp}\n.option method=gear\n'


def dut_lines(netlist):
    if netlist == 'extracted':
        txt = (GEN / 'char_atb.ext.spice').read_text()
        return '.include char_atb.ext.spice\n', txt
    return '.include char_atb.sch.spice\n', None


def chain(port, sel_f, sel_s):
    """Force chain on ATB0, sense chain on ATB1, both on node `port`."""
    return (f'XLF {port} LF {sel_f} VDD 0 atb_leaf_f\nXGF LF GF {sel_f} VDD 0 atb_grp\nXPF ATB0 GF {sel_f} VDD 0 atb_pad\n'
            f'XLS {port} LS {sel_s} VDD 0 atb_leaf_s\nXGS LS GS {sel_s} VDD 0 atb_grp\nXPS ATB1 GS {sel_s} VDD 0 atb_pad\n')


def dut_inst(prefix=''):
    # 1 Tohm keeper on every node so an untapped node (a MIM top plate) has a DC path
    keep = ''.join(f'RK_{prefix}{p} {prefix}{p} 0 1e12\n' for p in st.PORTS[:-1])
    return 'X' + (prefix or 'DUT') + ' ' + ' '.join(prefix + p if p != 'VSS' else '0' for p in st.PORTS) + f' {st.CELL}\n' + keep


ATB_INC = ''.join(f'.include {c}.pex.spice\n' for c in ('atb_leaf_f', 'atb_leaf_s', 'atb_grp', 'atb_pad'))


def iv_deck(port, corner, temp, vdd, netlist, currents, meter_ohm=1e9):
    """Forced-current sweep: ATB0 current source, ATB1 into a 10 Mohm meter.
    Reference: the same DUT node driven directly by the same current (no ATB)."""
    inc, _ = dut_lines(netlist)
    t = header(corner, temp) + inc + ATB_INC
    t += f'VDD VDD 0 {vdd}\nVSEL SEL 0 {vdd}\n' + dut_inst() + chain(port, 'SEL', 'SEL')
    t += f'IF 0 ATB0 0\nRM ATB1 0 {meter_ohm:g}\nCP0 ATB0 0 2p\nCP1 ATB1 0 2p\n'
    # reference copy of the DUT, forced directly
    t += dut_inst('R_')
    t += f'IR 0 R_{port} 0\n'
    t += '.control\n'
    for k, i in enumerate(currents):
        t += (f'alter IF dc = {i}\nalter IR dc = {i}\nop\n'
              f'let pf = v(atb0)\nlet pn = v({port})\nlet ps = v(atb1)\nlet pr = v(R_{port})\n'
              f'echo "PT {k} {i} $&pf $&pn $&ps $&pr"\n')
    t += '.endc\n.end\n'
    return t


def run_deck(work, name, deck):
    work.mkdir(parents=True, exist_ok=True)
    r = ck.ngspice(work, name + '.spice', deck)
    out = (work / (name + '.spice.log')).read_text()
    pts = [tuple(float(x) for x in l.split()[1:]) for l in out.splitlines() if l.startswith('PT ')]
    meas = {m.group(1): float(m.group(2)) for m in re.finditer(r'^([a-z_0-9]+)\s*=\s*([-+0-9.eE]+)', out, re.M)}
    errs = [l for l in out.splitlines() if l.lower().startswith('error') or 'singular' in l.lower()][:5]
    return dict(points=pts, meas=meas, errors=errs, rc=r.returncode)


CUR_MOS = [1e-7, 1e-6, 1e-5, 3e-5, 1e-4]
CUR_RES = [1e-6, 1e-5, 5e-5, 1e-4]


def iv_job(port, corner, temp, vdd, netlist, meter_ohm=1e9):
    cur = CUR_RES if port.startswith('RES') else CUR_MOS
    work = SCRATCH / 'sims' / netlist
    work.mkdir(parents=True, exist_ok=True)
    name = f'iv_{port}_{corner}_{temp}_{vdd}_m{meter_ohm:.0e}'
    r = run_deck(work, name, iv_deck(port, corner, temp, vdd, netlist, cur, meter_ohm))
    rows = []
    for k, i, vf, vn, vs, vref in r['points']:
        rows.append(dict(i_a=i, v_force_pad=vf, v_node=vn, v_sense_pad=vs, v_direct=vref,
                         sense_err_mv=(vs - vn) * 1e3, path_err_mv=(vs - vref) * 1e3, force_drop_mv=(vf - vn) * 1e3))
    return dict(port=port, corner=corner, temp_c=temp, vdd=vdd, netlist=netlist, meter_ohm=meter_ohm, deck=str(work / (name + '.spice')),
                rows=rows, errors=r['errors'], complete=len(rows) == len(cur))


def mim_deck(sel_code_port, corner, temp, vdd, netlist, f=100e3):
    """LCR-meter view from the ATB0 pad: 1 V AC at f, read the pad admittance.
    sel_code_port = None -> pad selected with no leaf closed (bus de-embed)."""
    inc, _ = dut_lines(netlist)
    t = header(corner, temp) + inc + ATB_INC
    t += f'VDD VDD 0 {vdd}\nVON ON 0 {vdd}\nVOFF OFF 0 0\n' + dut_inst()
    # every passive node gets its force leaf; only the selected one is closed
    for p in ('RES_A', 'RES_B', 'MIM_A', 'MIM_B'):
        s = 'ON' if p == sel_code_port else 'OFF'
        t += f'XLF_{p} {p} LF {s} VDD 0 atb_leaf_f\n'
    t += 'XGF LF GF ON VDD 0 atb_grp\nXPF ATB0 GF ON VDD 0 atb_pad\nCP0 ATB0 0 2p\n'
    t += 'VAC SRC 0 DC 1.0 AC 1\nRS SRC ATB0 1\n'
    t += f'.control\nac lin 1 {f} {f}\nlet y = -i(VAC)/(v(atb0))\nlet cap = imag(y)/(2*3.14159265*{f})\nlet g = real(y)\n' \
         'let c0 = cap\nlet g0 = g\necho "CAP $&c0 $&g0"\n.endc\n.end\n'
    return t


def mim_job(corner, temp, vdd, netlist):
    work = SCRATCH / 'sims' / netlist
    work.mkdir(parents=True, exist_ok=True)
    out = {}
    for sel in (None, 'MIM_A', 'MIM_B'):
        name = f'mim_{sel or "open"}_{corner}_{temp}'
        deck = mim_deck(sel, corner, temp, vdd, netlist)
        ck.ngspice(work, name + '.spice', deck)
        log_ = (work / (name + '.spice.log')).read_text()
        m = [l.split() for l in log_.splitlines() if l.startswith('CAP ')]
        out[sel or 'open'] = dict(c_f=float(m[-1][1]), g_s=float(m[-1][2])) if m else None
    # direct (no ATB) capacitance of each side of the DUT for comparison
    t = header(corner, temp) + dut_lines(netlist)[0] + dut_inst() + \
        'VA MIM_A 0 DC 1 AC 1\nVB MIM_B 0 DC 1 AC 1\n.control\nac lin 1 100k 100k\n' \
        'let ca = -imag(i(VA))/(2*3.14159265*100e3)\nlet cb = -imag(i(VB))/(2*3.14159265*100e3)\n' \
        'let a0 = ca\nlet b0 = cb\necho "DIR $&a0 $&b0"\n.endc\n.end\n'
    name = f'mim_direct_{corner}_{temp}'
    ck.ngspice(work, name + '.spice', t)
    m = [l.split() for l in (work / (name + '.spice.log')).read_text().splitlines() if l.startswith('DIR ')]
    direct = dict(a=float(m[-1][1]), b=float(m[-1][2])) if m else None
    return dict(corner=corner, temp_c=temp, vdd=vdd, netlist=netlist, pad=out, direct=direct)


def safe_job(corner, temp, vdd, netlist):
    """ATB open (all selects 0): supply ramp 0 -> vdd in 1 us with every node
    tapped by its sense and force leaves; report DUT current (VSS) and node
    voltages. Also: bench error, ATB0 forced to 3.63 V on every node in turn."""
    work = SCRATCH / 'sims' / netlist
    work.mkdir(parents=True, exist_ok=True)
    t = header(corner, temp) + dut_lines(netlist)[0] + ATB_INC
    t += f'VDD VDD 0 PWL(0 0 1u {vdd})\nVSS_DUT VSSD 0 0\n'
    t += 'XDUT ' + ' '.join(p if p != 'VSS' else 'VSSD' for p in st.PORTS) + f' {st.CELL}\n'
    t += ''.join(f'RK_{p} {p} 0 1e12\n' for p in st.PORTS[:-1])
    for p in st.PORTS[:-1]:
        t += f'XLF_{p} {p} BF 0 VDD 0 atb_leaf_f\nXLS_{p} {p} BS 0 VDD 0 atb_leaf_s\n'
    t += 'XGF BF GF 0 VDD 0 atb_grp\nXGS BS GS 0 VDD 0 atb_grp\n'
    t += 'XPF ATB0 GF 0 VDD 0 atb_pad\nXPS ATB1 GS 0 VDD 0 atb_pad\nRB0 ATB0 0 1meg\nRB1 ATB1 0 1meg\n'
    t += '.tran 5n 3u\n.control\nrun\nlet idut = abs(i(VSS_DUT))\nmeas tran idut_max max idut from=0 to=3u\n'
    t += 'meas tran idut_end avg idut from=2.5u to=3u\n'
    for p in st.PORTS[:-1]:
        t += f'meas tran vmax_{p.lower()} max v({p}) from=0 to=3u\n'
    t += '.endc\n.end\n'
    name = f'safe_ramp_{corner}_{temp}'
    r = run_deck(work, name, t)
    res = dict(corner=corner, temp_c=temp, vdd=vdd, netlist=netlist, ramp=r['meas'], errors=r['errors'])
    # bench error: 3.63 V on ATB0 into each node, with the force chain closed
    over = {}
    for p in st.PORTS[:-1]:
        t = header(corner, temp) + dut_lines(netlist)[0] + ATB_INC + f'VDD VDD 0 {vdd}\nVSEL SEL 0 {vdd}\n' + dut_inst()
        t += f'XLF {p} LF SEL VDD 0 atb_leaf_f\nXGF LF GF SEL VDD 0 atb_grp\nXPF ATB0 GF SEL VDD 0 atb_pad\n'
        t += 'VF ATB0 0 3.63\n.control\nop\nlet a0 = i(VF)\nlet b0 = i(VDD)\necho "OV $&a0 $&b0"\n.endc\n.end\n'
        name = f'over_{p}_{corner}_{temp}'
        ck.ngspice(work, name + '.spice', t)
        m = [l.split() for l in (work / (name + '.spice.log')).read_text().splitlines() if l.startswith('OV ')]
        over[p] = dict(i_pad_ma=-float(m[-1][1]) * 1e3, i_vdd_ma=-float(m[-1][2]) * 1e3) if m else None
    res['overdrive_3v63'] = over
    return res


def sims(netlist='extracted', workers=4, only=None):
    stage_atb(SCRATCH / 'sims' / netlist)
    out = dict(iv=[], mim=[], safe=[], iv_meter10meg=[])
    jobs = []
    with ThreadPoolExecutor(workers) as ex:
        for corner, temp, vdd in CORNERS:
            for p in st.PORTS[:-1]:
                if p.startswith('MIM'):
                    continue
                jobs.append(('iv', ex.submit(iv_job, p, corner, temp, vdd, netlist)))
            jobs.append(('mim', ex.submit(mim_job, corner, temp, vdd, netlist)))
        for p in st.PORTS[:-1]:
            if not p.startswith('MIM'):
                jobs.append(('iv_meter10meg', ex.submit(iv_job, p, 'typical', 27, 3.3, netlist, 1e7)))
        for corner, temp in [('typical', 27), ('ff', 85), ('ss', 0)]:
            jobs.append(('safe', ex.submit(safe_job, corner, temp, 3.63, netlist)))
        for kind, f in jobs:
            out[kind].append(f.result())
    (GEN / f'char_atb-sims-{netlist}.json').write_text(json.dumps(out, indent=1) + '\n')
    return out


# ------------------------------------------------------------------ evidence
SENSE_LIMIT_MV = 1.0        # sense pad vs node
PATH_LIMIT_MV = 2.0         # sense pad vs the same DUT forced directly (no ATB)
FORCE_PAD_MAX_V = 3.3       # force pad must stay inside the rail at the max current
MIM_ERR_LIMIT = 0.03        # de-embedded C vs direct C
SAFE_I_DC_LIMIT_NA = 100.0     # DUT current with the bus open, settled after the ramp (2.5-3 us)
SAFE_I_PEAK_LIMIT_UA = 10.0    # DUT current peak during the 1 us ramp (displacement + node junctions)
# Revision note: the first run used one 100 nA limit on the ramp peak. The peak
# (0.62 uA tt) is MIM/junction displacement while VDD ramps and the leaf wells
# couple the open nodes to ~0.5 V; it is harmless, so the gate is now on the
# settled current with a separate 10 uA peak ceiling. Both numbers are recorded.


def evidence():
    phys = json.loads((GEN / 'char_atb-physical.json').read_text())
    s = json.loads((GEN / 'char_atb-sims-extracted.json').read_text())
    fails = []
    worst = dict(sense_mv=0, path_mv=0, force_pad_v=0)
    for j in s['iv']:
        if not j['complete'] or j['errors']:
            fails.append(f"iv {j['port']} {j['corner']}: incomplete/errors {j['errors']}")
        for r in j['rows']:
            worst['sense_mv'] = max(worst['sense_mv'], abs(r['sense_err_mv']))
            worst['path_mv'] = max(worst['path_mv'], abs(r['path_err_mv']))
            worst['force_pad_v'] = max(worst['force_pad_v'], r['v_force_pad'])
            if abs(r['sense_err_mv']) > SENSE_LIMIT_MV or abs(r['path_err_mv']) > PATH_LIMIT_MV:
                fails.append(f"iv {j['port']} {j['corner']} {r['i_a']:g} A: sense {r['sense_err_mv']:.3f} path {r['path_err_mv']:.3f} mV")
            if r['v_force_pad'] > FORCE_PAD_MAX_V:
                fails.append(f"iv {j['port']} {j['corner']} {r['i_a']:g} A: force pad {r['v_force_pad']:.3f} V")
    mim_rows = []
    for j in s['mim']:
        p, d = j['pad'], j['direct']
        if not (p.get('open') and p.get('MIM_A') and p.get('MIM_B') and d):
            fails.append(f"mim {j['corner']}: missing result")
            continue
        ca = p['MIM_A']['c_f'] - p['open']['c_f']
        cb = p['MIM_B']['c_f'] - p['open']['c_f']
        ea, eb = ca / d['a'] - 1, cb / d['b'] - 1
        mm_meas = (ca - cb) / ((ca + cb) / 2)
        mm_true = (d['a'] - d['b']) / ((d['a'] + d['b']) / 2)
        mim_rows.append(dict(corner=j['corner'], temp_c=j['temp_c'], c_bus_open_pf=p['open']['c_f'] * 1e12,
                             c_a_deembedded_pf=ca * 1e12, c_b_deembedded_pf=cb * 1e12,
                             c_a_direct_pf=d['a'] * 1e12, c_b_direct_pf=d['b'] * 1e12,
                             err_a=ea, err_b=eb, mismatch_meas=mm_meas, mismatch_direct=mm_true))
        if max(abs(ea), abs(eb)) > MIM_ERR_LIMIT:
            fails.append(f"mim {j['corner']}: de-embed error {ea:.4f}/{eb:.4f}")
    safe_rows = []
    for j in s['safe']:
        m = j['ramp']
        imax, iend = m.get('idut_max'), m.get('idut_end')
        if imax is None or iend is None or j['errors']:
            fails.append(f"safe {j['corner']}: no result {j['errors']}")
        else:
            if iend * 1e9 > SAFE_I_DC_LIMIT_NA:
                fails.append(f"safe {j['corner']}: settled DUT current {iend * 1e9:.1f} nA with bus open")
            if imax * 1e6 > SAFE_I_PEAK_LIMIT_UA:
                fails.append(f"safe {j['corner']}: ramp peak DUT current {imax * 1e6:.2f} uA")
        for p_, o in (j['overdrive_3v63'] or {}).items():
            if o is None:
                fails.append(f"safe {j['corner']}: overdrive {p_} no result")
            elif abs(o['i_vdd_ma']) > 0.01:
                fails.append(f"safe {j['corner']}: overdrive {p_} pulls {o['i_vdd_ma']:.3f} mA from VDD")
        safe_rows.append(dict(corner=j['corner'], temp_c=j['temp_c'], vdd=j['vdd'],
                              i_dut_peak_na=None if imax is None else imax * 1e9,
                              i_dut_settled_na=None if iend is None else iend * 1e9,
                              v_node_max={k[5:]: v for k, v in m.items() if k.startswith('vmax_')},
                              overdrive_3v63=j['overdrive_3v63']))
    gx = phys.get('gds_export', {})
    clean_ok = (phys.get('drc_count') == 0 and phys.get('lvs_unique') and gx.get('pass') and phys.get('lef_pins_match_ports'))
    srcs = {p.name: sha(p) for p in [HERE / 'structures.py', HERE / 'run_char.py', HERE / f'{st.CELL}.spice',
                                     HERE.parent / 'converters' / 'lib' / 'convkit.py', HERE.parent / 'converters' / 'flow.py']}
    srcs.update({f'atb_reference/{p.name}': sha(p) for p in sorted(ATB_DIR.glob('*.spice'))})
    gen = {p.name: sha(p) for p in sorted(GEN.glob('char_atb*')) if p.suffix in ('.gds', '.lef', '.spice', '.mag')}
    iv_fail = [f for f in fails if f.startswith('iv')]
    mim_fail = [f for f in fails if f.startswith('mim')]
    safe_fail = [f for f in fails if f.startswith('safe')]
    rec = dict(
        block='char_atb', cell=st.CELL, generated_utc=time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
        source_hashes=srcs, generated_hashes=gen,
        images=dict(analog=ck.image_id(ck.ANALOG_IMAGE), digital=ck.image_id(ck.DIGITAL_IMAGE)),
        atb_codes={p: st.ATB_CODE[p] for p in st.PORTS[:-1]},
        replicas=[dict(code=c, port=p, model=m, w_um=w, l_um=l, fingers=n, size_source=src) for c, p, m, w, l, n, src in st.REPLICAS],
        size_um=phys.get('size_um') or phys.get('size'),
        criteria=dict(sense_err_mv=SENSE_LIMIT_MV, path_err_mv=PATH_LIMIT_MV, force_pad_max_v=FORCE_PAD_MAX_V,
                      mim_deembed_err=MIM_ERR_LIMIT, safe_dut_settled_na=SAFE_I_DC_LIMIT_NA,
                      safe_dut_peak_ua=SAFE_I_PEAK_LIMIT_UA, sense_meter_ohm=1e9),
        tests=dict(
            safe=dict(state='pass' if not safe_fail else 'fail', cases=safe_rows, failures=safe_fail,
                      note='No VDD connection in the cell. Ramp 0->3.63 V in 1 us with all ATB leaves open; '
                           'overdrive: ATB0 held at 3.63 V into each node with its force chain closed (bench error).'),
            clean=dict(state='pass' if clean_ok else 'fail', magic_drc=phys.get('drc_count'), lvs=phys.get('lvs'),
                       lvs_unique=phys.get('lvs_unique'), gds_export=gx, lef_pins=phys.get('lef_pins')),
            observable=dict(state='pass' if not (iv_fail or mim_fail) else 'fail', worst=worst, mim=mim_rows,
                            failures=iv_fail + mim_fail,
                            note='Extracted DUT + extracted ATB leaf_f/leaf_s/grp/pad (island_support default-mode PEX). '
                                 'Forced current on ATB0, Kelvin sense on ATB1 into 10 Mohm; MIM by 100 kHz pad admittance '
                                 'with the open-bus reading subtracted.'),
            fallback=dict(state='waived', note='Characterization structure; no function to fall back from.')),
    )
    p = GEN / 'char_atb-evidence.json'
    p.write_text(json.dumps(rec, indent=1) + '\n')
    return rec, fails


