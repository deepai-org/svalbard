def log(*a):
    print(time.strftime('%H:%M:%S'), *a, flush=True)


def sha(p):
    return 'sha256:' + hashlib.sha256(Path(p).read_bytes()).hexdigest()


# ------------------------------------------------------------------ physical
LEF_TCL = '''crashbackups stop
load {cell}
select top cell
lef write {cell}.lef -hide
quit -noprompt
'''


def publish_rename(c, sch):
    """gds_uniquify the published char_atb.gds and round-trip LVS it (speed.verify_gds)."""
    sys.path.insert(0, str(HERE.parent))
    import gds_uniquify as gu
    import speed
    ren = gu.uniquify(GEN / 'char_atb.gds', c.name)
    return dict(ren, **speed.verify_gds(GEN / 'char_atb.gds', c.name, sch))


def layout():
    c = st.circuit()
    work = SCRATCH / 'layout'
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    sch = c.spice(include_macros=False)
    (HERE / f'{c.name}.spice').write_text('* generated by structures.py; do not edit\n' + sch)
    L = ck.Layout(c, work).build()
    L.write()
    log('drc', L.report['drc_count'])
    (work / f'{c.name}.lvs_sch.spice').write_text(sch)
    res = ck.lvs(work, f'{c.name}.lvs.spice', c.name, f'{c.name}.lvs_sch.spice', c.name)
    log('lvs', res['final'], res['match_unique'])
    gx = convflow.export_gds(work, c)
    (work / 'lef.tcl').write_text(LEF_TCL.format(cell=c.name))
    r = ck.docker(ck.DIGITAL_IMAGE, work, f'magic -dnull -noconsole -rcfile {ck.PDK}/libs.tech/magic/gf180mcuD.magicrc /work/lef.tcl')
    (work / 'lef.log').write_text(r.stdout + r.stderr)
    GEN.mkdir(exist_ok=True)
    for src, dst in [(f'{c.name}.gds', 'char_atb.gds'), (f'{c.name}.ext.spice', 'char_atb.ext.spice'),
                     (f'{c.name}.lvs.spice', 'char_atb.lvs.spice'), ('lvs.txt', 'char_atb-lvs.txt'),
                     (f'{c.name}.lef', 'char_atb.lef'), (f'{c.name}_flat.mag', 'char_atb.mag')]:
        if (work / src).exists():
            shutil.copy(work / src, GEN / dst)
    # Block-unique subcell names (CH3): convkit used to name PCell masters prim_N in every block,
    # and the chip merge is by name.  Rename below the top, then round-trip LVS the published file.
    info_rename = publish_rename(c, work / f'{c.name}.lvs_sch.spice')
    (GEN / 'char_atb-drc.txt').write_text((work / 'drc-count.txt').read_text() + (work / 'drc-details.txt').read_text())
    if (work / 'klayout-drc.lyrdb').exists():
        shutil.copy(work / 'klayout-drc.lyrdb', GEN / 'char_atb-klayout-drc.lyrdb')
    lef = (GEN / 'char_atb.lef').read_text() if (GEN / 'char_atb.lef').exists() else ''
    lef_pins = sorted(set(re.findall(r'^\s*PIN (\S+)', lef, re.M)))
    info = dict(L.report, lvs=res['final'], lvs_unique=res['match_unique'], gds_export=gx,
                lef_pins=lef_pins, lef_pins_match_ports=lef_pins == sorted(c.ports),
                published_gds_after_rename=info_rename)
    (GEN / 'char_atb-physical.json').write_text(json.dumps(info, indent=1, default=str) + '\n')
    return info


