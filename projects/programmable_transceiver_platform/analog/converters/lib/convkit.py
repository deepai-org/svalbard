    name: str
    model: str          # nfet_03v3 / pfet_03v3
    w: float
    l: float
    d: str
    g: str
    s: str
    b: str
    m: int = 1
    flip: bool = False
    x: float = None

    def spice(self):
        return [f'X{self.name}_{i} {self.d} {self.g} {self.s} {self.b} {self.model} '
                f'w={self.w}u l={self.l}u' for i in range(self.m)]

    def key(self):
        return ('mos', self.model, self.w, self.l)

    def units(self):
        return [(f'{self.name}_{i}', {'D': self.d, 'G': self.g, 'S': self.s, 'B': self.b})
                for i in range(self.m)]


