"""Netlist-to-layout kit for the converter family (Magic + Netgen + ngspice).

Every circuit is a flat list of primitive devices (GF180 PCells generated by
Magic's own device generators, MIM caps, high-R poly resistors) plus at most a
few standard-cell macros hardened by LibreLane. The layout is built by a
deliberately simple, correct-by-construction router:

* devices sit in horizontal rows, bottoms aligned;
* every terminal leaves its device on a private Metal2 riser, upward for
  MOS source/drain, resistor end A and MIM top plate, downward for MOS gate,
  body ties, resistor end B and MIM bottom plate;
* risers land on Metal3 tracks in the channel directly above (or below) the
  row; tracks are shared between nets by left-edge interval packing;
* a net present in more than one channel (or a block port) also gets a Metal4
  trunk in the trunk bank on the west side, which joins its tracks.

Area is spent freely (the converter allocations are large); the payoff is that
DRC and LVS follow from construction and every step is inspectable.
"""
