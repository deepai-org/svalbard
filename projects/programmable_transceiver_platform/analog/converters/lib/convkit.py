@dataclasses.dataclass
class Macro:
    """A LibreLane-hardened standard-cell macro (GDS + LEF + powered netlist)."""
    name: str
    cell: str
    gds: Path
    lef: Path
    netlist: Path       # powered gate-level Verilog (pnl.v)
    pins: dict          # macro pin -> net (power pins VDD/VSS included)
    strap_dir: str = 'down'
    x: float = None

    def spice(self):
        order = macro_pin_order(self)
        return [f'X{self.name} ' + ' '.join(self.pins[p] for p in order) + f' {self.cell}']

    def key(self):
        return ('macro', self.cell)

    def units(self):
        return [(self.name, dict(self.pins))]


def macro_pin_order(macro):
    text = macro.netlist.read_text()
    head = re.search(r'module\s+' + re.escape(macro.cell) + r'\s*\((.*?)\);', text, re.S).group(1)
    ports = [p.strip() for p in head.split(',') if p.strip()]
    widths = dict()
    for kind, rng, names in re.findall(r'\b(input|output|inout)\s*(\[\d+:\d+\])?\s*([^;]+);', text):
        for n in names.split(','):
            widths[n.strip()] = rng
    order = []
    for p in ports:
        rng = widths.get(p, '')
        if rng:
            hi, lo = map(int, rng[1:-1].split(':'))
            order += [f'{p}[{i}]' for i in range(lo, hi + 1)]
        else:
            order.append(p)
    return order


def verilog_to_spice(macro, stdcell_spice):
    """Convert a powered gate-level netlist into a SPICE subcircuit."""
    cellpins = {}
    for m in re.finditer(r'^\.SUBCKT\s+(\S+)\s+(.*)$', Path(stdcell_spice).read_text(), re.M | re.I):
        cellpins[m.group(1)] = m.group(2).split()
    text = macro.netlist.read_text()
    text = re.sub(r'//.*', '', text)
    body = text[text.index(');', text.index('module')) + 2:text.index('endmodule')]
    order = macro_pin_order(macro)
    lines = [f'.subckt {macro.cell} ' + ' '.join(order)]
    assigns = []
    for stmt in body.split(';'):
        stmt = ' '.join(stmt.split())
        if not stmt or re.match(r'^(input|output|inout|wire)\b', stmt):
            continue
        if stmt.startswith('assign'):
            assigns.append(stmt)
            continue
        m = re.match(r'^(\S+)\s+(\\\S+|[A-Za-z_][\w$]*)\s*\((.*)\)$', stmt)
        if not m:
            raise ValueError('Unparsed netlist statement: ' + stmt)
        cell, inst, conns = m.group(1), m.group(2).replace(' ', ''), m.group(3)
        pins = dict(re.findall(r'\.(\w+)\s*\(\s*([^()]*?)\s*\)', conns))
        if cell not in cellpins:
            raise ValueError('Unknown cell ' + cell)
        nets = []
        for p in cellpins[cell]:
            n = pins.get(p, '').strip()
            if not n:
                n = {'VNW': 'VDD', 'VPW': 'VSS'}.get(p) or f'nc_{inst}_{p}'
            nets.append(spice_net(n))
        lines.append(f'X{spice_net(inst)} ' + ' '.join(nets) + f' {cell}')
    if assigns:
        raise ValueError('assign statements in hardened netlist: ' + '; '.join(assigns[:3]))
    lines.append('.ends')
    return '\n'.join(lines) + '\n'


def spice_net(n):
    n = n.strip().lstrip('\\')
    if n in ("1'b0", "1'h0"):
        return 'VSS'
    if n in ("1'b1", "1'h1"):
        return 'VDD'
    return re.sub(r'[^A-Za-z0-9_\[\]]', '_', n)


# ---------------------------------------------------------------- circuit
@dataclasses.dataclass
class Circuit:
    name: str
    ports: list
    devices: list
    rows: list = None            # list of lists of device names (layout order)
    wide_nets: dict = None       # net -> track/trunk width (um)
    notes: list = dataclasses.field(default_factory=list)

    def device(self, name):
        return next(d for d in self.devices if d.name == name)

    def spice(self, include_macros=True, stdcell_spice=None):
        lines = []
        if include_macros:
            for d in self.devices:
                if isinstance(d, Macro):
                    lines.append(verilog_to_spice(d, stdcell_spice))
        lines.append(f'.subckt {self.name} ' + ' '.join(self.ports))
        for d in self.devices:
            lines += d.spice()
        lines.append('.ends')
        return '\n'.join(lines) + '\n'

    def nets(self):
        out = set(self.ports)
        for d in self.devices:
            for _, pins in d.units():
                out |= set(pins.values())
        return sorted(out)


# ---------------------------------------------------------------- PCells
def gencell_cmd(key):
    if key[0] == 'mos':
        _, model, w, l = key
        return (f'magic::gencell_makecell gf180mcu::{model} w {w} l {l} nf 1 guard 1 topc 0 botc 1 '
                'full_metal 1 gate_to_polycont 0.6 gate_extension 0.8 diff_gate_space 0.3')
    if key[0] == 'cap':
        return f'magic::gencell_makecell gf180mcu::cap_mim_2p0fF w {key[1]} l {key[2]}'
    if key[0] == 'res':
        return f'magic::gencell_makecell gf180mcu::ppolyf_u_1k w {key[1]} l {key[2]} guard 1 full_metal 1'
    raise ValueError(key)


def mag_rects(path):
    layer, out, props = None, {}, {}
    for line in Path(path).read_text().splitlines():
        if line.startswith('<< '):
            layer = line[3:-3]
        elif line.startswith('rect ') and layer:
            out.setdefault(layer, []).append([int(v) * GRID for v in line.split()[1:5]])
        elif line.startswith('string FIXED_BBOX'):
            props['bbox'] = [int(v) * GRID for v in line.split()[2:6]]
    return out, props


def bbox_of(rects):
    return [min(r[0] for r in rects), min(r[1] for r in rects),
            max(r[2] for r in rects), max(r[3] for r in rects)]


def pcell_geometry(key, path):
    """Base geometry in PCell coordinates (unflipped)."""
    r, props = mag_rects(path)
    geom = [v for k, rs in r.items() if k != 'checkpaint' for v in rs]
    box = bbox_of(geom)
    g = dict(box=box)
    if key[0] == 'mos':
        dc = r.get('ndiffc') or r.get('pdiffc')
        s, d = min(dc, key=lambda a: a[0]), max(dc, key=lambda a: a[2])
        pc = r['polycontact'][0]
        bar = min(r['metal1'], key=lambda a: a[1])
        g['pins'] = {
            'S': dict(x=(s[0] + s[2]) / 2, y=s[3] - 0.25, side=+1, pad='m1'),
            'D': dict(x=(d[0] + d[2]) / 2, y=d[3] - 0.25, side=+1, pad='m1'),
            'G': dict(x=(pc[0] + pc[2]) / 2, y=(pc[1] + pc[3]) / 2, side=-1, pad='m1'),
            'B': dict(x=bar[0] + 0.35, y=(bar[1] + bar[3]) / 2, side=-1, pad='m1')}
        if abs(g['pins']['B']['x'] - g['pins']['G']['x']) < 0.85:
            raise ValueError('Body tap too close to gate riser')
    elif key[0] == 'cap':
        cc = r['mimcapcontact'][0]
        g['cc'] = ((cc[0] + cc[2]) / 2, (cc[1] + cc[3]) / 2, cc)
        g['plate'] = bbox_of(r['metal4'])
    elif key[0] == 'res':
        pcs = sorted(r['polycontact'], key=lambda a: a[1])
        bar = min(r['metal1'], key=lambda a: a[1])
        lo, hi = pcs[0], pcs[-1]
        g['pins'] = {
            'A': dict(x=(hi[0] + hi[2]) / 2 - 0.4, y=(hi[1] + hi[3]) / 2, side=+1, pad='m1'),
            'B': dict(x=(lo[0] + lo[2]) / 2 + 0.4, y=(lo[1] + lo[3]) / 2, side=-1, pad='m1'),
            'SUB': dict(x=bar[0] + 0.35, y=(bar[1] + bar[3]) / 2, side=-1, pad='m1')}
    return g


def macro_geometry(macro):
    text = Path(macro.lef).read_text()
    size = re.search(r'SIZE\s+([\d.]+)\s+BY\s+([\d.]+)', text)
    w, h = float(size.group(1)), float(size.group(2))
    pins = {}
    for m in re.finditer(r'PIN (\S+)(.*?)END \1', text, re.S):
        name = m.group(1)
        rects = [(layer, list(map(float, rr.split()))) for layer, rr in
                 re.findall(r'LAYER (\S+) ;\s*RECT ([\d. -]+) ;', m.group(2))]
        if name in ('VDD', 'VSS'):
            up = macro.strap_dir == 'up'
            pins[name] = [dict(x=(a[0] + a[2]) / 2, y=a[3] if up else a[1], dir='up' if up else 'down',
                               pad='strap', width=a[2] - a[0]) for layer, a in rects if layer == 'Metal4']
            continue
        layer, a = rects[0]
        if layer != 'Metal2':
            raise ValueError('Macro pin not on Metal2: ' + name)
        x = (a[0] + a[2]) / 2
        if a[1] < 1:
            pins[name] = [dict(x=x, y=a[1] + 0.28, dir='down', pad='edge')]
        elif a[3] > h - 1:
            pins[name] = [dict(x=x, y=a[3] - 0.28, dir='up', pad='edge')]
        else:
            raise ValueError('Macro pin not on north/south edge: ' + name)
    return dict(box=[0, 0, w, h], pins=pins)


def instance_view(dev, g):
    """Pins (list per pin name) and outline for one placed unit, local coords."""
    if isinstance(dev, Macro):
        return g['box'], g['pins']
    flip = getattr(dev, 'flip', False)
    if isinstance(dev, (Mos, Res)):
        box = list(g['box'])
        pins = {}
        for n, p in g['pins'].items():
            y = -p['y'] if flip else p['y']
            side = -p['side'] if flip else p['side']
            pins[n] = [dict(x=p['x'], y=y, dir='up' if side > 0 else 'down', pad=p['pad'])]
        if flip:
            box = [box[0], -box[3], box[2], -box[1]]
        return box, pins
    # MIM capacitor: modes instead of flipping.
    cx, cy, cc = g['cc']
    plate = g['plate']
    pins = {}
    bdir, tdir = dev.bdir, dev.tdir
    pins['BOT'] = [dict(x=cx, y=plate[1] if bdir == 'down' else plate[3], dir=bdir, pad='mimbot')]
    box = list(g['box'])
    box = [min(box[0], plate[0]), min(box[1], plate[1] - 1.3), max(box[2], plate[2]),
           max(box[3], plate[3] + 1.3)]
    if tdir != bdir:
        pins['T'] = [dict(x=cx, y=cc[3] if tdir == 'up' else cc[1], dir=tdir, pad='mimtop',
                          stack_y=(plate[3] + 1.6) if tdir == 'up' else (plate[1] - 1.6))]
        box[1] = min(box[1], plate[1] - 1.9) if tdir == 'down' else box[1]
        box[3] = max(box[3], plate[3] + 1.9) if tdir == 'up' else box[3]
    else:
        xs = plate[0] - 1.6
        pins['T'] = [dict(x=xs, y=cy, dir=tdir, pad='mimside', cx=cx)]
        box[0] = min(box[0], xs - 0.6)
    return box, pins


