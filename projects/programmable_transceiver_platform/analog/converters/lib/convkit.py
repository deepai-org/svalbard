def _lef_gate_area(lef):
    """{pin: ANTENNAGATEAREA um^2} from a macro LEF."""
    out, pin = {}, None
    for line in Path(lef).read_text().splitlines():
        tok = line.split()
        if tok[:1] == ['PIN']:
            pin = tok[1]
        elif tok[:1] == ['ANTENNAGATEAREA'] and pin:
            out[pin] = out.get(pin, 0.) + float(tok[1])
        elif tok[:1] == ['END'] and len(tok) > 1 and tok[1] == pin:
            pin = None
    return out


class Layout:
    W = 0.4              # default wire width (M2..M4)
    SP = 0.6             # track spacing

    def __init__(self, circuit, work, *, device_gap=2.0, row_gap=0.6):
        self.c = circuit
        self.work = Path(work).resolve()
        self.gap = getattr(circuit, 'device_gap', device_gap)
        self.row_gap = row_gap
        self.cmds = []
        self.report = {}
        self.net = None           # net of the shapes being drawn (antenna-diode planning)
        self.shapes = []          # (layer, x1, y1, x2, y2, net)
        self.antenna_diodes = []

    # -- painting helpers
    def rect(self, layer, x1, y1, x2, y2):
        self.cmds.append(f'box values {q(min(x1, x2))} {q(min(y1, y2))} {q(max(x1, x2))} {q(max(y1, y2))}')
        self.cmds.append(f'paint {layer}')
        self.shapes.append((layer, q(min(x1, x2)), q(min(y1, y2)), q(max(x1, x2)), q(max(y1, y2)), self.net))

    def via(self, x, y, lo, hi):
        half = {1: .19, 2: .2, 3: .2, 4: .2, 5: .22}
        for m in range(lo, hi + 1):
            self.rect(f'metal{m}', x - half[m], y - half[m], x + half[m], y + half[m])
        for m in range(lo, hi):
            h = .13 if m == 1 else .14
            self.rect(f'via{m}', x - h, y - h, x + h, y + h)

    def wire(self, layer, x1, y1, x2, y2, w=None):
        w = w or (.44 if layer == 'metal5' else self.W)
        if x1 != x2 and y1 != y2:
            raise ValueError('Manhattan only')
        self.rect(layer, min(x1, x2) - w / 2, min(y1, y2) - w / 2, max(x1, x2) + w / 2, max(y1, y2) + w / 2)

    def magic(self, script, timeout=3600, allow_failure=False):
        (self.work / script[0]).write_text(script[1])
        r = docker(DIGITAL_IMAGE, self.work,
                   f'magic -dnull -noconsole -rcfile {PDK}/libs.tech/magic/gf180mcuD.magicrc /work/{script[0]}',
                   timeout=timeout)
        (self.work / (script[0] + '.log')).write_text(r.stdout + r.stderr)
        if r.returncode and not allow_failure:
            raise RuntimeError(f'magic failed: {script[0]}\n' + (r.stdout + r.stderr)[-3000:])
        return r

    def primitives(self):
        keys = sorted({d.key() for d in self.c.devices if not isinstance(d, Macro)}, key=str)
        # Block-unique primitive cell names: a generic `prim_N` collides with other blocks' cells of
        # the same name (and different contents) when the chip GDS merges every block's layout.
        self.prim = {k: f'{self.c.name}__prim_{i}' for i, k in enumerate(keys)}
        cmds = ['crashbackups stop', 'load primitive_workspace']
        for k, name in self.prim.items():
            cmds += ['units internal', f'set cell [{gencell_cmd(k)}]', 'load $cell', f'save {name}',
                     'load primitive_workspace']
        cmds.append('quit -noprompt')
        self.magic(('primitives.tcl', '\n'.join(cmds) + '\n'))
        self.geom = {k: pcell_geometry(k, self.work / (name + '.mag')) for k, name in self.prim.items()}
        for d in self.c.devices:
            if isinstance(d, Macro):
                self.geom[d.key()] = macro_geometry(d)

    # -- placement: rows bottom to top, x left to right (optional explicit x)
    def place(self):
        rows = self.c.rows or [[d.name for d in self.c.devices]]
        seen = set()
        self.rows = []
        for names in rows:
            row = []
            x = 0.0
            for n in names:
                d = self.c.device(n)
                seen.add(n)
                fixed = getattr(d, 'x', None)
                for i, (uname, pins) in enumerate(d.units()):
                    box, vp = instance_view(d, self.geom[d.key()])
                    # d.x, when given, is the absolute origin of the first unit.
                    ox = fixed if (fixed is not None and i == 0) else x - box[0]
                    if row and ox + box[0] < row[-1]['ox'] + row[-1]['box'][2] + 0.6:
                        raise ValueError(f'Overlapping placement at {uname}')
                    row.append(dict(name=uname, dev=d, pins=pins, view=vp, box=box, ox=ox, oy=0.0))
                    x = ox + box[2] + self.gap
            lo = min(u['box'][1] for u in row)
            hi = max(u['box'][3] for u in row)
            kind = 'mos'
            if any(isinstance(u['dev'], Macro) for u in row):
                kind = 'macro'
            elif any(isinstance(u['dev'], Cap) for u in row):
                kind = 'cap'
            self.rows.append(dict(units=row, lo=lo, hi=hi, kind=kind,
                                  x0=min(u['ox'] + u['box'][0] for u in row),
                                  x1=max(u['ox'] + u['box'][2] for u in row)))
        missing = {d.name for d in self.c.devices} - seen
        if missing:
            raise ValueError('Unplaced devices: ' + ', '.join(sorted(missing)))

    def build(self):
        self.primitives()
        self.place()
        R = len(self.rows)
        wide = self.c.wide_nets or {}
        acc = []
        for r, row in enumerate(self.rows):
            for u in row['units']:
                for pin, net in u['pins'].items():
                    for p in u['view'][pin]:
                        ch = r + 1 if p['dir'] == 'up' else r
                        acc.append(dict(row=r, ch=ch, net=net, x=q(u['ox'] + p['x']), ry=p['y'], p=p, unit=u))
        bych = {}
        for a in acc:
            if a['p']['pad'] != 'strap':      # straps are Metal4, risers Metal2
                bych.setdefault((a['ch'], a['p']['dir']), []).append(a)
        for key, lst in bych.items():
            lst.sort(key=lambda a: a['x'])
            for a, b in zip(lst, lst[1:]):
                if a['net'] != b['net'] and b['x'] - a['x'] < 0.79:
                    raise ValueError(f'Riser collision in channel {key}: {a["net"]}@{a["x"]} {b["net"]}@{b["x"]}')
        net_ch = {}
        for a in acc:
            net_ch.setdefault(a['net'], set()).add(a['ch'])
        trunk_nets, jumpers = [], {}
        for n, chs in net_ch.items():
            lo, hi = min(chs), max(chs)
            if n in self.c.ports:
                trunk_nets.append(n)
            elif lo != hi:
                crossed = [self.rows[r]['kind'] for r in range(lo, hi)]
                if all(k == 'mos' for k in crossed) and n not in wide:
                    jumpers[n] = (lo, hi)
                else:
                    trunk_nets.append(n)
        tx, x = {}, -2.0
        for n in sorted(trunk_nets, key=lambda n: (n not in wide, n)):
            w = wide.get(n, self.W)
            x -= w / 2
            tx[n] = q(x)
            x -= w / 2 + (1.0 if w > self.W else self.SP)
        bank_left = x - 1.0
        # M4 occupancy: (x, ch_lo, ch_hi, half_width)
        m4 = []
        for a in acc:
            if a['p']['pad'] == 'strap':
                m4.append((a['x'], a['ch'], a['ch'], a['p']['width'] / 2))

        def m4_free(xc, lo, hi, half):
            return all(abs(xc - sx) >= half + sh + 0.6 or hi < slo or lo > shi for sx, slo, shi, sh in m4)

        def pick_x(center, xmin, xmax, lo, hi, half=0.2):
            for k in range(0, 8000):
                for c_ in ((center + k * 0.5), (center - k * 0.5)):
                    c_ = q(c_)
                    if xmin <= c_ <= xmax and m4_free(c_, lo, hi, half):
                        m4.append((c_, lo, hi, half))
                        return c_
            raise ValueError('No free M4 column')

        jx = {}
        for n, (lo, hi) in sorted(jumpers.items(), key=lambda kv: kv[1][1] - kv[1][0]):
            xs = sorted(a['x'] for a in acc if a['net'] == n)
            row_lo = max(self.rows[r]['x0'] for r in range(lo, hi)) + 1
            row_hi = min(self.rows[r]['x1'] for r in range(lo, hi)) - 1
            jx[n] = pick_x((xs[0] + xs[-1]) / 2, row_lo, row_hi, lo, hi)
        self.jx = jx
        chans = {}
        for a in acc:
            chans.setdefault(a['ch'], []).append(a)

        def part(n, d, split):
            return (n, ('lo' if d == 'up' else 'hi')) if n in split else (n, 'all')

        def solve(c, split):
            lst = chans.get(c, [])
            spans = {}
            for a in lst:
                k = part(a['net'], a['p']['dir'], split)
                l0, h0 = spans.get(k, (a['x'], a['x']))
                spans[k] = (min(l0, a['x']), max(h0, a['x']))
            anchor = {}
            for (n, pt) in list(spans):
                if pt in ('all', 'lo'):
                    anchor[n] = (n, pt)
            for n in split:
                if (n, 'lo') not in spans:
                    anchor[n] = (n, 'hi')
            for n, k in anchor.items():
                if n in tx:
                    spans[k] = (tx[n], spans[k][1])
            for n, (lo, hi) in jumpers.items():
                if lo <= c <= hi and (c in (lo, hi) or n in anchor):
                    k = anchor.get(n, (n, 'all'))
                    l0, h0 = spans.get(k, (jx[n], jx[n]))
                    spans[k] = (min(l0, jx[n]), max(h0, jx[n]))
                    anchor[n] = k
            local = {}
            for n in split:
                if (n, 'lo') in spans and (n, 'hi') in spans:
                    a1, b1 = spans[(n, 'lo')]
                    a2, b2 = spans[(n, 'hi')]
                    xmin, xmax = max(a1, a2, 0.0), min(b1, b2)
                    if xmin > xmax:
                        xmin, xmax = 0.0, max(b1, b2)
                    half = max(wide.get(n, self.W), self.W) / 2
                    xl = pick_x((xmin + xmax) / 2, 0.0, 1e6, c, c, half)
                    local[n] = xl
                    for k in ((n, 'lo'), (n, 'hi')):
                        spans[k] = (min(spans[k][0], xl), max(spans[k][1], xl))
            below = {k: set() for k in spans}
            ups = [a for a in lst if a['p']['dir'] == 'up' and a['p']['pad'] != 'strap']
            downs = sorted((a for a in lst if a['p']['dir'] == 'down' and a['p']['pad'] != 'strap'),
                           key=lambda a: a['x'])
            import bisect
            dxs = [a['x'] for a in downs]
            for u in ups:
                i = bisect.bisect_left(dxs, u['x'] - 1.0)
                while i < len(downs) and downs[i]['x'] <= u['x'] + 1.0:
                    if downs[i]['net'] != u['net']:
                        below[part(downs[i]['net'], 'down', split)].add(part(u['net'], 'up', split))
                    i += 1
            for n in local:
                below[(n, 'hi')].add((n, 'lo'))
            unplaced = set(spans)
            tracks = []
            while unplaced:
                cur = []
                for k in sorted(unplaced, key=lambda k: (spans[k][0], k)):
                    if (below[k] - {k}) & unplaced:
                        continue
                    w = wide.get(k[0], self.W)
                    if cur and (w > self.W or any(wide.get(m[0], self.W) > self.W for m in cur)):
                        continue
                    if any(not (spans[k][0] > spans[m][1] + 1.4 or spans[k][1] < spans[m][0] - 1.4) for m in cur):
                        continue
                    cur.append(k)
                if not cur:
                    return None, unplaced
                unplaced -= set(cur)
                tracks.append(cur)
            return (tracks, spans, anchor, local, split), None

        chan_tracks = {}
        self.splits = {}
        for c in range(R + 1):
            m4_mark = len(m4)
            res, bad = solve(c, set())
            if res is None:
                del m4[m4_mark:]
                bidir = {a['net'] for a in chans.get(c, []) if a['p']['dir'] == 'up'} & \
                        {a['net'] for a in chans.get(c, []) if a['p']['dir'] == 'down'}
                res, bad = solve(c, bidir)
                if res is None:
                    raise ValueError(f'Vertical constraint cycle in channel {c}: ' + str(sorted(bad))[:400])
                self.splits[c] = sorted(bidir)
            chan_tracks[c] = res
        # Vertical placement.
        track_y = {}
        y = 0.0
        self.row_y = []
        for c in range(R + 1):
            tracks = chan_tracks[c][0]
            y += 0.9
            for t in tracks:
                w = max(wide.get(k[0], self.W) for k in t)
                ty = q(y + w / 2)
                for k in t:
                    track_y[(c, k)] = ty
                y += w + self.SP
            y += 0.3
            if c < R:
                row = self.rows[c]
                y += self.row_gap
                oy = q(y - row['lo'])
                self.row_y.append(oy)
                for u in row['units']:
                    u['oy'] = oy
                y = oy + row['hi'] + self.row_gap
        top = y
        for a in acc:
            a['y'] = q(self.row_y[a['row']] + a['ry'])
            a['key'] = part(a['net'], a['p']['dir'], chan_tracks[a['ch']][4])
        # Paint.
        cmds = self.cmds
        cmds += ['crashbackups stop']
        import shutil
        for d in self.c.devices:
            if isinstance(d, Macro):
                shutil.copy(d.gds, self.work / Path(d.gds).name)   # only /work is mounted
                cmds += [f'gds read {Path(d.gds).name}']
        cmds += [f'load {self.c.name}', 'units microns']
        for row in self.rows:
            for u in row['units']:
                d = u['dev']
                cell = d.cell if isinstance(d, Macro) else self.prim[d.key()]
                orient = ' v' if getattr(d, 'flip', False) and not isinstance(d, (Cap, Macro)) else ''
                cmds += [f'getcell {cell}{orient} child 0 0 parent {q(u["ox"])} {q(u["oy"])}',
                         f'identify X{u["name"]}']
        grp = {}
        for a in acc:
            grp.setdefault((a['ch'], a['key']), []).append(a['x'])
        skip = set()
        for (c, k), xs in grp.items():
            last = None
            for xv in sorted(set(xs)):
                if last is not None and xv - last < 0.7:
                    skip.add((c, k, xv))
                else:
                    last = xv

        def landing(a, ty):
            if (a['ch'], a['key'], a['x']) not in skip:
                self.via(a['x'], ty, 2, 3)

        for a in acc:
            ty = track_y[(a['ch'], a['key'])]
            x, y0, p = a['x'], a['y'], a['p']
            pad = p['pad']
            self.net = a['net']
            sgn = 1 if p['dir'] == 'up' else -1
            if pad == 'm1':
                self.via(x, y0, 1, 2)
                self.wire('metal2', x, y0, x, ty)
                landing(a, ty)
            elif pad == 'edge':
                self.wire('metal2', x, y0, x, ty)
                landing(a, ty)
            elif pad == 'strap':
                w = p['width']
                self.rect('metal4', x - w / 2, ty + 0.2 * sgn, x + w / 2, y0 - 0.5 * sgn)
                self.via(x, ty, 3, 4)
            elif pad == 'mimtop':
                ys = q(a['unit']['oy'] + p['stack_y'])
                self.rect('metal5', x - .22, y0 - 0.5 * sgn, x + .22, ys + .22 * sgn)
                self.via(x, ys, 2, 5)
                self.wire('metal2', x, ys, x, ty)
                landing(a, ty)
            elif pad == 'mimside':
                cx = q(a['unit']['ox'] + p['cx'])
                self.rect('metal5', x - .22, y0 - .22, cx, y0 + .22)
                self.via(x, y0, 2, 5)
                self.wire('metal2', x, y0, x, ty)
                landing(a, ty)
            elif pad == 'mimbot':
                ys = q(y0 + 0.6 * sgn)
                self.rect('metal4', x - .3, ys + .3 * sgn, x + .3, y0 - 0.1 * sgn)
                self.via(x, ys, 2, 4)
                self.wire('metal2', x, ys, x, ty)
                landing(a, ty)
            else:
                raise ValueError(pad)
        for (c, k), xs in grp.items():
            xs = sorted(set(xs))
            ty = track_y[(c, k)]
            self.net = k[0]
            for x1, x2 in zip(xs, xs[1:]):
                if x2 - x1 < 1.2:
                    self.rect('metal2', x1, ty - .2, x2, ty + .2)
        for c, (tracks, spans, anchor, local, split) in chan_tracks.items():
            for k, (lo, hi) in spans.items():
                n = k[0]
                self.net = n
                ty = track_y[(c, k)]
                w = wide.get(n, self.W)
                left = lo - 0.3
                if anchor.get(n) == k and n in tx:
                    left = min(left, tx[n] - w / 2)
                self.rect('metal3', left, ty - w / 2, hi + 0.3, ty + w / 2)
                if anchor.get(n) == k:
                    if n in tx:
                        self.via(tx[n], ty, 3, 4)
                        if w >= 1.6:
                            for d_ in (-w / 2 + 0.3, w / 2 - 0.3):
                                self.via(q(tx[n] + d_), ty, 3, 4)
                    if n in jx and jumpers[n][0] <= c <= jumpers[n][1]:
                        self.via(jx[n], ty, 3, 4)
            for n, xl in local.items():
                self.net = n
                w = max(wide.get(n, self.W), self.W)
                y1, y2 = track_y[(c, (n, 'lo'))], track_y[(c, (n, 'hi'))]
                self.rect('metal4', xl - w / 2, y1 - .2, xl + w / 2, y2 + .2)
                for yv in (y1, y2):
                    self.via(xl, yv, 3, 4)
                    if w >= 1.6:
                        for d_ in (-w / 2 + 0.3, w / 2 - 0.3):
                            self.via(q(xl + d_), yv, 3, 4)
        for n, (lo, hi) in jumpers.items():
            self.net = n
            self.rect('metal4', jx[n] - .2, track_y[(lo, chan_tracks[lo][2][n])] - .2,
                      jx[n] + .2, track_y[(hi, chan_tracks[hi][2][n])] + .2)
        for n, x in tx.items():
            ys = [track_y[(c, chan_tracks[c][2][n])] for c in net_ch[n]]
            lo, hi = min(ys), max(ys)
            if n in self.c.ports:
                hi = top + 1.0
            w = wide.get(n, self.W)
            self.net = n
            self.rect('metal4', x - w / 2, lo - 0.3, x + w / 2, hi + 0.3)
        self.net = None
        self._antenna(acc)
        labelled = set()
        for (c, k), ty in sorted(track_y.items()):
            n = k[0]
            if n in labelled:
                continue
            lo = chan_tracks[c][1][k][0]
            cmds += [f'box values {q(lo - 0.1)} {q(ty - .1)} {q(lo + .1)} {q(ty + .1)}',
                     f'label {n} FreeSans 0.1 0 0 0 c metal3']
            labelled.add(n)
        for i, p in enumerate(self.c.ports, 1):
            x = tx[p]
            w = wide.get(p, self.W)
            cmds += [f'box values {q(x - w / 2)} {q(top + 0.8)} {q(x + w / 2)} {q(top + 1.3)}',
                     f'label {p} FreeSans 0.2 0 0 0 c metal4', f'port make {i}']
        right = max(r['x1'] for r in self.rows)
        self.bbox = [q(bank_left), 0.0, q(right + 1.0), q(top + 1.5)]
        self.report.update(trunk_nets=len(tx), jumpers=len(jx), split_channels=self.splits,
                           channels={c: len(v[0]) for c, v in chan_tracks.items()},
                           bbox_um=self.bbox,
                           area_um2=round((self.bbox[2] - self.bbox[0]) * (self.bbox[3] - self.bbox[1]), 1))
        return self

    def _antenna(self, acc):
        """Antenna diodes (KLayout ANT.16): gate-only partial nets with long M2-M4 get an N+/Psub
        diode under their own M3/M4 wire (analog/antenna_diodes.py); see lvs_reference()."""
        terms, keep, taps = [], [], []
        for row in self.rows:
            for u in row['units']:
                box = (u['ox'] + u['box'][0], u['oy'] + u['box'][1], u['ox'] + u['box'][2], u['oy'] + u['box'][3])
                keep.append(box)
                if isinstance(u['dev'], Mos) and u['dev'].model.startswith('nfet'):
                    taps.append(box)
        for a in acc:
            d, pin = a['unit']['dev'], next((k for k, v in a['unit']['pins'].items() if v == a['net'] and
                                             a['p'] in a['unit']['view'].get(k, [])), None)
            if isinstance(d, Mos):
                kind = 'g' if pin == 'G' else 'sd' if pin in ('D', 'S') else 'x'
                terms.append((a['x'], a['y'], a['net'], kind, d.w * d.l if kind == 'g' else 0.))
            elif isinstance(d, Macro):
                # Hardened macro input pins (LEF ANTENNAGATEAREA) are gates seen from this level's
                # routing; the macro's internal diodes are not reliably on the partial net here.
                # The deck also counts the macro's own internal routing on the same partial net,
                # which this level cannot see (dac_logic hold_zero: 233 um internal M3 + 151 um
                # block M3 -> ratio 464, RC-21/K3).  Derate the gate area so the block wire alone
                # must stay below MARGIN*LIMIT/MACRO_GATE_DERATE (diode is sized for the same).
                ga = _lef_gate_area(d.lef).get(pin, 0.)
                terms.append((a['x'], a['y'], a['net'], 'g' if ga > 0 else 'sd', ga * MACRO_GATE_DERATE))
        req = ad.requests_from_shapes(self.shapes, terms)
        cmds, self.antenna_diodes = ad.plan(req, [s[:5] for s in self.shapes], keep, taps=taps)
        self.cmds += cmds
        self.report['antenna_diodes'] = self.antenna_diodes

    def lvs_reference(self, text):
        """Schematic text + this layout's antenna diodes in the top subckt."""
        lines = ad.spice_lines(self.antenna_diodes)
        if not lines:
            return text
        k = text.index(f'.subckt {self.c.name} ')
        e = text.index('.ends', k)
        return text[:e] + '\n'.join(lines) + '\n' + text[e:]

    def write(self):
        name = self.c.name
        cmds = list(self.cmds)
        cmds += ['select top cell', 'save',
                 'drc on', 'drc check', 'drc catchup',
                 'set f [open drc-count.txt w]', 'puts $f [drc list count total]', 'close $f',
                 'set f [open drc-details.txt w]', 'puts $f [drc listall why]', 'close $f',
                 'extract all',
                 'ext2spice lvs', f'ext2spice -o {name}.lvs.spice',
                 # Simulation netlist is exported flat: the hierarchical export
                 # leaves macro-port coupling nodes floating (singular matrix).
                 'ext2spice default', 'ext2spice format ngspice', 'ext2spice cthresh 0',
                 'ext2spice hierarchy off', 'ext2spice subcircuit top on', 'ext2spice scale off',
                 f'ext2spice -o {name}.ext.spice',
                 # Published GDS is written by the analog image (flow.export_gds);
                 # this canary copy is a scratch reference only.
                 f'gds write {name}.canary.gds',
                 'quit -noprompt']
        self.magic(('layout.tcl', '\n'.join(cmds) + '\n'))
        drc = (self.work / 'drc-count.txt').read_text().strip()
        self.report['drc_count'] = int(drc) if drc.isdigit() else drc
        return self


def lvs(work, layout_spice, layout_cell, schematic_spice, schematic_cell, out='lvs.txt'):
    cmd = (f'netgen -batch lvs "{layout_spice} {layout_cell}" "{schematic_spice} {schematic_cell}" '
           f'{PDK}/libs.tech/netgen/gf180mcuD_setup.tcl {out}')
    r = docker(DIGITAL_IMAGE, work, cmd, timeout=3600)
    (Path(work) / (out + '.log')).write_text(r.stdout + r.stderr)
    text = (Path(work) / out).read_text() if (Path(work) / out).exists() else ''
    unique = 'Netlists match uniquely' in (r.stdout + text)
    final = re.findall(r'Final result:\s*(.*)', r.stdout + text)
    return dict(match_unique=unique and 'Circuits match uniquely' in (r.stdout + text),
                final=final[-1] if final else None, stdout_tail=r.stdout[-1500:])


