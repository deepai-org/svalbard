#!/usr/bin/env bash
# Reproduce the core-support (POR + biasgen) qualification evidence.
#
#   run_core_support.sh [fetch] [verify] [clean] [tapeout] [canary] [dist] [sim] [summarize]
#   (no arguments = all steps, in that order)
#
# Heavy outputs go to scratch/core_support/ (gitignored).  Written into this
# directory: evidence/core_support_evidence.json, the patched biasgen tapeout
# views (biasgen_tapeout/), and the bias-distribution layouts
# (distribution/generated/).  Container runs use --network none and bounded
# CPU/memory; "fetch" is the only step that needs the network (git clone of the
# pinned Avalon standard-cell library).
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/../../../.." && pwd)"
scratch="${SVALBARD_SCRATCH:-$repo/scratch}/core_support"
analog_image="docker.io/hpretl/iic-osic-tools@sha256:89641950bbf247c522188629992b6271e391e38372ca0f8e3c850480874948a3"
analog_image_id="sha256:bd7a702bef0b85f5ebf67efca449f270fbeb185380ead204559fcd2457959305"
digital_image="${CORE_SUPPORT_DIGITAL_IMAGE:-svalbard/librelane-gf180-canary:2026.08}"
avalon_url="https://github.com/AvalonSemiconductors/gf180mcu_as_sc_mcu7t3v3"
avalon_rev="b41119fdaa7873bb149a84d5b81fd9d8dc037a34"
cpus="${CORE_SUPPORT_CPUS:-8}"
memory="${CORE_SUPPORT_MEMORY:-16g}"
sim_jobs="${CORE_SUPPORT_SIM_JOBS:-6}"

steps=("$@")
[[ ${#steps[@]} -gt 0 ]] || steps=(fetch verify clean tapeout canary dist sim summarize)
want() { local s; for s in "${steps[@]}"; do [[ "$s" == "$1" ]] && return 0; done; return 1; }

mkdir -p "$scratch/work"

if want fetch; then
  if [[ ! -d "$scratch/avalon_src/.git" ]]; then
    git clone -q "$avalon_url" "$scratch/avalon_src"
  fi
  git -C "$scratch/avalon_src" fetch -q origin "$avalon_rev" 2>/dev/null || true
  git -C "$scratch/avalon_src" checkout -q "$avalon_rev"
  rm -rf "$scratch/avalon_lib"; mkdir -p "$scratch/avalon_lib"
  cp -r "$scratch/avalon_src/pdk/libs.ref/gf180mcu_as_sc_mcu7t3v3/." "$scratch/avalon_lib/"
  cp -r "$scratch/avalon_src/pdk/libs.tech/xschem" "$scratch/avalon_lib/xschem"
  echo "fetch: Avalon std cells at $avalon_rev"
fi

if want verify; then
  (cd "$here/por" && sha256sum --quiet -c ../manifest/por.sha256)
  (cd "$here/biasgen" && sha256sum --quiet -c ../manifest/biasgen.sha256)
  (cd "$here/bandgap" && sha256sum --quiet -c ../manifest/bandgap.sha256)
  [[ "$(git -C "$scratch/avalon_src" rev-parse HEAD)" == "$avalon_rev" ]]
  [[ "$(docker image inspect "$analog_image" --format '{{.Id}} {{.Architecture}}')" == "$analog_image_id arm64" ]]
  echo "verify: vendored sources match manifests; Avalon and analog image pinned"
fi

docker_common=(--rm --platform linux/arm64 --network none --cpus "$cpus" --memory "$memory"
  --memory-swap "$memory" --pids-limit 1024 --user "$(id -u):$(id -g)" --env HOME=/tmp --env OMP_NUM_THREADS=1
  --mount "type=bind,src=$here,dst=/src,readonly"
  --mount "type=bind,src=$scratch/work,dst=/work" --workdir /work
  --tmpfs /tmp:size=1g,mode=1777)

analog() {
  docker run "${docker_common[@]}" \
    --env PDK=gf180mcuD --env PDK_ROOT=/foss/pdks --env PDKPATH=/foss/pdks/gf180mcuD \
    --mount "type=bind,src=$scratch/avalon_lib,dst=/foss/pdks/gf180mcuD/libs.ref/gf180mcu_as_sc_mcu7t3v3,readonly" \
    --entrypoint /bin/bash "$analog_image" -lc "$1"
}

if want clean; then
  analog "BLOCKS='por biasgen biasgen_patched bandgap bandgap_patched' KLAYOUT_THREADS=$cpus bash /src/flow/clean_flow.sh" \
    2>&1 | grep -v '^\[INFO\]' | tee "$scratch/work/clean.log"
fi

if want tapeout; then
  # The patched biasgen (pin fix + vfb compensation) GDS/LEF, generated by the
  # clean step from the patched Magic view, is the tapeout source.
  t="$here/biasgen_tapeout"; mkdir -p "$t"
  cp "$scratch/work/clean/biasgen_patched/tapeout/gf180mcu_ocd_ip__biasgen.gds.gz" \
     "$scratch/work/clean/biasgen_patched/tapeout/gf180mcu_ocd_ip__biasgen.lef" "$t/"
  (cd "$scratch/work/clean/biasgen_patched/src" && tar --sort=name --mtime=@0 --owner=0 --group=0 --numeric-owner \
     -cf - magic xschem | gzip -n > "$t/patched_sources.tar.gz")
  (cd "$t" && sha256sum gf180mcu_ocd_ip__biasgen.gds.gz gf180mcu_ocd_ip__biasgen.lef patched_sources.tar.gz > SHA256SUMS)
  echo "tapeout: patched biasgen GDS/LEF copied to $t"
fi

if want canary; then
  if docker image inspect "$digital_image" >/dev/null 2>&1; then
    docker run "${docker_common[@]}" \
      --mount "type=bind,src=$scratch/avalon_lib,dst=/pdk/gf180mcuD/libs.ref/gf180mcu_as_sc_mcu7t3v3,readonly" \
      --entrypoint /bin/sh "$digital_image" /src/flow/crosscheck_canary.sh | tee "$scratch/work/canary.log"
    docker image inspect "$digital_image" --format '{{.Id}}' > "$scratch/work/canary_image_id.txt"
    analog 'for b in por biasgen biasgen_patched bandgap bandgap_patched; do c=gf180mcu_ocd_ip__${b%_patched}; klayout -b -r /src/flow/hres_check.py -rd gds=/work/canary/$b/canary_export.gds -rd top=$c -rd out=/work/canary/$b/hres_negative_control.json; done' \
      2>&1 | grep -v '^\[INFO\]' >> "$scratch/work/canary.log"
  else
    echo "canary: $digital_image not present; cross-check skipped" | tee "$scratch/work/canary.log"
  fi
fi

if want dist; then
  # bias distribution: layout (digital image Magic via analog/rf_tx/layoutlib.py), Netgen LVS, KLayout DRC
  (cd "$here/distribution" && python3 generate_dist.py --scratch "$scratch/dist" --publish "$here/distribution/generated") \
    | tee "$scratch/work/dist_layout.log"
fi

if want sim; then
  rm -rf "$scratch/work/sim"
  analog "cd /src/flow && SIM_JOBS=$sim_jobs python3 sim_core_support.py bg bg_pex bg_loop bg_probe bg_loop_coarse" \
    2>&1 | grep -v '^\[INFO\]' > "$scratch/work/bg_campaign.log"
  analog "cd /src/flow && SIM_JOBS=$sim_jobs python3 sim_core_support.py por por_pex" \
    2>&1 | grep -v '^\[INFO\]' > "$scratch/work/por_campaign.log"
  analog "cd /src/distribution && SIM_JOBS=$sim_jobs python3 sim_dist.py" \
    2>&1 | grep -v '^\[INFO\]' > "$scratch/work/dist_campaign.log"
  analog "cd /src/flow && SIM_JOBS=$sim_jobs python3 sim_bandgap.py" \
    2>&1 | grep -v '^\[INFO\]' > "$scratch/work/bandgap_campaign.log"
fi

if want summarize; then
  python3 "$here/flow/summarize.py" --work "$scratch/work" --out "$here/evidence" \
    --analog-image "$analog_image" --analog-image-id "$analog_image_id" --avalon-rev "$avalon_rev"
fi
