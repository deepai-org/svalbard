"""Protocol-independent RX/USB control exclusion boundary.

Behavioral first pass only: comparator accuracy, asynchronous hazards, sticky
fault storage and transistor/layout implementation remain separate obligations.
Analog TERM_VCM and HS_PBIAS are not generated by this block.
"""
import json
from design import PROJECT

CONTROLS = ('TERM_ENABLE', 'DIFF_ENABLE', 'DIV_ENABLE', 'BYPASS_ENABLE',
            'HS_P', 'HS_N', 'FS_HIGH_P', 'FS_HIGH_N', 'FS_LOW_P', 'FS_LOW_N',
            'PULLUP_P', 'PULLUP_N', 'PULLDOWN_P', 'PULLDOWN_N')
# Pairwise electrical conflicts; HS current drive plus shunt termination is
# intentionally legal. FS drive may coexist with a role's passive pull resistors.
CONFLICTS = (
    ('DIV_ENABLE', 'BYPASS_ENABLE'),
    ('DIFF_ENABLE', 'TERM_ENABLE'),
    *((a, b) for a in ('DIFF_ENABLE', 'TERM_ENABLE')
      for b in ('FS_HIGH_P', 'FS_HIGH_N')),
    *((a, b) for a in ('DIFF_ENABLE',)
      for b in ('FS_LOW_P', 'FS_LOW_N')),
    *((a, b) for a in ('HS_P', 'HS_N')
      for b in ('FS_HIGH_P', 'FS_HIGH_N', 'FS_LOW_P', 'FS_LOW_N')),
    ('FS_HIGH_P', 'FS_LOW_P'), ('FS_HIGH_N', 'FS_LOW_N'),
)


def resolve(requests, supply_v, reset, qualified):
    unknown = set(requests) - set(CONTROLS)
    if unknown:
        raise ValueError('Unknown controls: ' + ', '.join(sorted(unknown)))
    low, high = json.loads((PROJECT/'spec/analog-architecture.json').read_text())['blocks']['monitor']['parameters']['supply_window_v']
    conflicts = [(a, b) for a, b in CONFLICTS if requests.get(a, False) and requests.get(b, False)]
    enabled = bool(low <= supply_v <= high and not reset and qualified and not conflicts)
    return {name: bool(requests.get(name, False) and enabled) for name in CONTROLS}, conflicts


def spice():
    low, high = json.loads((PROJECT/'spec/analog-architecture.json').read_text())['blocks']['monitor']['parameters']['supply_window_v']
    ports = ['VDD', 'VSS', 'RESET', 'QUALIFIED', 'CONFLICT']
    ports += ['REQ_'+name for name in CONTROLS] + list(CONTROLS)
    lines = ['.subckt receive_control_guard ' + ' '.join(ports)]
    # Command inputs use fixed 1.65V decision levels. They do not become
    # spuriously true merely because the local supply collapses.
    terms = [f'((V(REQ_{a},VSS)>1.65)*(V(REQ_{b},VSS)>1.65))' for a, b in CONFLICTS]
    lines += ['BCONFLICT CONFLICT VSS V=(' + '+'.join(terms) + '>0)',
              f'BVALID VALID VSS V=(V(VDD,VSS)>={low})*(V(VDD,VSS)<={high})*(V(RESET,VSS)<1.65)*(V(QUALIFIED,VSS)>1.65)*(V(CONFLICT,VSS)<.5)']
    for name in CONTROLS:
        lines.append(f'B{name} {name} VSS V=V(VDD,VSS)*V(VALID,VSS)*(V(REQ_{name},VSS)>1.65)')
    return '\n'.join(lines+['.ends receive_control_guard', ''])


def attach(deck, reset_source, qualified_source):
    """Route existing command sources through the guard; preserve pad/network."""
    for name in CONTROLS:
        old = f'B{name} {name} 0 '
        if deck.count(old) != 1:
            raise ValueError('Expected one behavioral command source for ' + name)
        deck = deck.replace(old, f'B{name} REQ_{name} 0 ')
    ports = ['VDD', 'VSS', 'PAD_RESET', 'PAD_QUALIFIED', 'PAD_CONFLICT']
    ports += ['REQ_'+name for name in CONTROLS] + list(CONTROLS)
    return (deck + spice() + 'XCONTROL_GUARD ' + ' '.join(ports) +
            ' receive_control_guard\n' +
            f'VPAD_RESET PAD_RESET VSS {reset_source}\n' +
            f'VPAD_QUALIFIED PAD_QUALIFIED VSS {qualified_source}\n')
