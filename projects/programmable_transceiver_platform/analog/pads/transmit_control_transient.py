"""Observe switching hazards in the extracted static TX mode interlock.

Qualification blanking is externally prescribed, not an implemented sequencer.
Output loads are diagnostic bounds, not extracted pad-control fanout.
"""
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np
from transmit_control_circuit import REQUESTS,build
from transmit_controls import CONFLICTS
from screen import run_spice,control


def pwl(events):
    return 'PWL('+' '.join(f'{t:g}n {v:g}' for t,v in events)+')'


def run(work,physical,pdk,blanking_ns=2.):
    if not 0.1 < blanking_ns < 9:raise ValueError("Blanking must fit between request events")
    work.mkdir(parents=True,exist_ok=False);model=physical.read_text();ports=build().ports
    definition=next(l.split() for l in model.splitlines() if l.startswith('.subckt '))
    if definition[2:]!=ports:raise ValueError('Wrong control ports')
    cases={};sequence=[(0,19),(20,4),(40,8),(60,5),(80,0),(100,1)]
    for cap in (50e-15,500e-15):
      for blanked in (False,True):
        name=f'{int(cap*1e15)}f_'+('blanked' if blanked else 'direct')
        deck=f'TX extracted control transitions\n.include {pdk}/design.ngspice\n.lib {pdk}/sm141064.ngspice typical\n.temp 27\n'+model
        deck+='XCTL '+' '.join(ports)+' '+definition[1]+'\nVSS VSS 0 0\n'
        deck+='VDD VDD 0 '+pwl([(0,3.3),(240,3.3),(241,0),(260,0)])+'\n'
        for bit,n in enumerate(REQUESTS):
            events=[(0,3.3*bool(sequence[0][1]&(1<<bit)))];old=events[0][1]
            for t,code in sequence[1:]:
                value=3.3*bool(code&(1<<bit));events.extend([(t,old),(t+.1,value)]);old=value
            events.append((260,old));deck+=f'VREQ_{n} REQ_{n} 0 '+pwl(events)+'\n'
            deck+=f'CLOAD_{n} EN_{n} VSS {cap}\n'
        qual=[(0,3.3)]
        if blanked:
            for t,code in sequence[1:]:qual.extend([(t-blanking_ns,3.3),(t-blanking_ns+.1,0),(t+blanking_ns,0),(t+blanking_ns+.1,3.3)])
        qual.extend([(160,3.3),(160.1,0),(180,0),(180.1,3.3),(260,3.3)])
        deck+='VQUAL QUALIFIED 0 '+pwl(qual)+'\n'
        deck+='VRESET RESET 0 '+pwl([(0,0),(120,0),(120.1,3.3),(140,3.3),(140.1,0),(260,0)])+'\n'
        deck+='VOK SUPPLY_OK 0 '+pwl([(0,3.3),(200,3.3),(200.1,0),(220,0),(220.1,3.3),(238,3.3),(238.1,0),(260,0)])+'\n'
        deck+=control(work,name,'tran 5p 260n','v(VDD) v(VALID) v(CONFLICT) '+' '.join('v(EN_'+n+')' for n in REQUESTS)+' i(VDD)')
        x=run_spice(work,name,deck)
        if not np.isfinite(x).all() or x[-1,0]<259.99e-9:raise ValueError('Incomplete transient')
        enabled={n:x[:,4+i]>2.31 for i,n in enumerate(REQUESTS)}
        overlap=np.zeros(len(x),dtype=bool)
        for a,b in CONFLICTS:overlap|=enabled[a]&enabled[b]
        dt=np.diff(x[:,0]);overlap_time=float(np.sum(dt[overlap[:-1]]))
        peaks={}
        for label,start,end in [('reset',125,139),('unqualified',165,179),('supply_invalid',205,219),('unpowered',245,259)]:
            z=x[(x[:,0]>=start*1e-9)&(x[:,0]<=end*1e-9),4:9]
            peaks[label]=float(z.max())
        cases[name]={'output_capacitance_f_per_pin':cap,'prescribed_qualification_blanking':blanked,'conflicting_outputs_above_0p7vdd_total_s':overlap_time,'first_overlap_s':float(x[np.flatnonzero(overlap)[0],0]) if overlap.any() else None,'off_window_max_output_v':peaks,'peak_supply_draw_a':float(max(0,-x[:,-1].min())),'output_extrema_v':[float(x[:,4:9].min()),float(x[:,4:9].max())]}
    report={'status':'extracted_control_transition_diagnostic_not_glitch_free_qualification','cases':cases,'threshold_v':2.31,'blanking_ns':blanking_ns,'scope':'Same extracted interlock throughout. Full-rail requests and fixed50/500fF load bounds. Configured qualification blanking is prescribed around request changes, not generated by hardware. No pad fanout, transistor supervisor or buffer-ready implementation. Conflicting overlap measured at0.7*3.3V; analog conduction below threshold remains possible.','source_sha256':{str(p.resolve()):hashlib.sha256(p.read_bytes()).hexdigest() for p in [Path(__file__),physical,Path(__file__).with_name('transmit_controls.py')]}}
    (work/'screen.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report,indent=2))

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    for n in ('output-dir','physical','pdk-model-dir'):p.add_argument('--'+n,type=Path,required=True)
    p.add_argument('--blanking-ns',type=float,default=2.)
    a=p.parse_args();run(a.output_dir.resolve(),a.physical.resolve(),a.pdk_model_dir.resolve(),a.blanking_ns)
