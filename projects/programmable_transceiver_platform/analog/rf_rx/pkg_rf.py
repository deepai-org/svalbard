#!/usr/bin/env python3
"""RF_RX bond / ground model for the pt_rf bond map (D-SPLIT-RFGND), and the same model on the old single-chip map for comparison.

  python3 pkg_rf.py model      writes generated/pkg-rf-bond-model.spice (subckts rfrx_bond_{RF,OLD}_{min,nom,max})
  python3 pkg_rf.py check      known answer, negative control, ground impedance, bounce conversion -> scratch/rf_rx/gnd/check.json

Wire geometry and the loop-inductance matrix: the pads owner's filament model (scratch/pads-core/lnagnd/bondl.py, read only),
cases min / nom / max = loop and plane bounds.  Here ALL 20 west bonds (55-74) are individual, coupled wires (the pads owner's
model kept six of them and lumped the rest).  Board end of each west wire by its pt_rf function (integration/chips/rf/bond_map.txt):
  provider ground finger            -> board ground directly (paddle / plane)
  provider supply finger            -> board ground through the 0201 path (1.2 / 1.8 / 2.6 nH; spec/power-delivery model cap0201_L)
  ground / supply on a SIGNAL finger -> board ground through trace + connector + carrier (2.0 / 5.8 / 7.5 nH, 0.1 ohm): no COB part
  signal (BB_I, BB_Q, RF_TX)        -> open (no current; their mutuals do not matter)
Bonds off the west edge are lumped (uncoupled): provider grounds 2.2 nH / n, provider supplies (2.3 nH + 0201) / n, signal-site
grounds / supplies (2.3 nH + carrier path) / n.  Each wire 0.25 ohm.  No on-die ring impedance; die decap is added by the user.
Ports as the pads owner's model: BRD_P BRD_N PAD_P PAD_N VSS VDD (board ground = node 0)."""
import sys, json, math, subprocess, os
from pathlib import Path
import numpy as np
HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
sys.path.insert(0, str(REPO / 'scratch' / 'pads-core' / 'lnagnd'))
import bondl as B                                    # noqa: E402  (pads owner's wire model, read only)
OUTF = HERE / 'generated' / 'pkg-rf-bond-model.spice'
WORK = REPO / 'scratch' / 'rf_rx' / 'gnd'
R_BOND = 0.25
L_SUPB = dict(min=1.2, nom=1.8, max=2.6)            # supply finger -> 1 uF
L_CAR = dict(min=2.0, nom=5.8, max=7.5)             # signal finger -> carrier ground (trace, connector, carrier)
P, N = 68, 67                                        # RF_RX_P / RF_RX_N bonds (PC-26 option B, kept on pt_rf)
WEST = list(range(55, 75))
# pt_rf west edge, bond -> kind (bond_map.txt; bond 74 = dvdd_pads[5] ... 55 = inputs[0])
RF = {74: 'sup', 73: 'gnd', 72: 'sup', 71: 'gnd', 70: 'sig', 69: 'sig', 68: 'rx', 67: 'rx', 66: 'sig', 65: 'sig', 64: 'sup', 63: 'gnd',
      62: 'xgnd', 61: 'xgnd', 60: 'xsup', 59: 'xgnd', 58: 'sup', 57: 'gnd', 56: 'sig', 55: 'sig'}
OLD = {**RF, 62: 'sig', 61: 'sig', 60: 'sig', 59: 'sig'}      # single-chip map, PC-26 B: 59-62 were AUX_CLK / REF_IN
# off-west bonds: (provider grounds, provider supplies, signal-site grounds, signal-site supplies)
REST = dict(RF=(6, 4, 6, 1), RFNC=(6, 4, 6, 1), OLD=(6, 4, 0, 0))
MAPS = dict(RF=RF, OLD=OLD)


def lmat(case):
    p = B.CASES[case]
    wires = [B.wire_segs(B.W0[k]['src'], B.W0[k]['dst'], p['h'], p['f'], p['H']) for k in WEST]
    return B.matrix(wires, p['zpl'])


def subckt(name, kinds, L, case, couple_rx=True):
    rest = REST[name.split('_')[0]]
    d = [f'.subckt rfrx_bond_{name} BRD_P BRD_N PAD_P PAD_N VSS VDD']
    act = [k for k in WEST if kinds[k] != 'sig']
    ix = {k: i for i, k in enumerate(WEST)}
    for k in act:
        t = kinds[k]
        brd = {'rx': 'BRD_P' if k == P else 'BRD_N'}.get(t, '0' if t == 'gnd' else f'f{k}')
        die = {'rx': 'PAD_P' if k == P else 'PAD_N', 'gnd': 'VSS', 'xgnd': 'VSS', 'sup': 'VDD', 'xsup': 'VDD'}[t]
        d += [f'Lb{k} {brd} m{k} {L[ix[k], ix[k]]:.5f}n', f'Rb{k} m{k} {die} {R_BOND}']
        if t == 'sup': d.append(f'Lf{k} f{k} 0 {L_SUPB[case]}n')
        if t in ('xgnd', 'xsup'): d += [f'Lf{k} f{k} r{k} {L_CAR[case]}n', f'Rf{k} r{k} 0 0.1']
    for a, i in enumerate(act):
        for j in act[a + 1:]:
            if not couple_rx and ((kinds[i] == 'rx') != (kinds[j] == 'rx')): continue
            d.append(f'Kb{i}_{j} Lb{i} Lb{j} {L[ix[i], ix[j]] / math.sqrt(L[ix[i], ix[i]] * L[ix[j], ix[j]]):.6f}')
    ng, ns, nxg, nxs = rest
    d += [f'Lgr VSS mgr {2.2 / ng:.4f}n', f'Rgr mgr 0 {R_BOND / ng:.4f}',
          f'Lsr VDD msr {(2.3 + L_SUPB[case]) / ns:.4f}n', f'Rsr msr 0 {R_BOND / ns:.4f}']
    if nxg: d += [f'Lxg VSS mxg {(2.3 + L_CAR[case]) / nxg:.4f}n', f'Rxg mxg 0 {(R_BOND + 0.1) / nxg:.4f}']
    if nxs: d += [f'Lxs VDD mxs {(2.3 + L_CAR[case]) / nxs:.4f}n', f'Rxs mxs 0 {(R_BOND + 0.1) / nxs:.4f}']
    return d + [f'.ends rfrx_bond_{name}']


def model():
    out = ['* RF_RX bond / ground model, pt_rf bond map (RF_*) and the old single-chip map (OLD_*). Generated by analog/rf_rx/pkg_rf.py;',
           '* wire matrix from scratch/pads-core/lnagnd/bondl.py (analytic filament model, not EM, not measured). See the docstring.']
    for case in ('min', 'nom', 'max'):
        L = lmat(case)
        for m in MAPS: out += subckt(f'{m}_{case}', MAPS[m], L, case)
        out += subckt(f'RFNC_{case}', RF, L, case, couple_rx=False)     # negative control: no coupling into the RX wires
    OUTF.write_text('\n'.join(out) + '\n'); print(OUTF, len(out), 'lines')


def ng(deck, name):
    WORK.mkdir(parents=True, exist_ok=True); f = WORK / f'{name}.cir'; f.write_text(deck)
    r = subprocess.run(['ngspice', '-b', str(f)], capture_output=True, text=True, timeout=300)
    (WORK / f'{name}.log').write_text(r.stdout[-6000:] + r.stderr[-2000:])
    v = {}
    for l in r.stdout.splitlines():
        s = l.split()
        if len(s) == 3 and s[1] == '=':
            try: v[s[0]] = float(s[2])
            except ValueError: pass
    return v


def check():
    """Z(die VSS -> board) with the die decap (5.4 nF, 0.1 ohm, VDD-VSS); bounce conversion = differential EMF between the RX pad
    ends (RX board ends at 0 through 50 ohm, pads open) per volt of die VSS; known answer: OLD vs the pads owner's B model."""
    res = {}
    pads = REPO / 'scratch' / 'reviews' / 'pads-core' / 'lna-bond-model.spice'
    fs = (78.125e6, 156.25e6, 2.421875e9, 5e9, 8e9)
    for case in ('min', 'nom', 'max'):
        for m in ('RF', 'OLD', 'RFNC', 'PADS_B'):
            sub = f'rfrx_bond_{m}_{case}' if m != 'PADS_B' else f'rfrx_bond_B_{case}'
            inc = OUTF if m != 'PADS_B' else pads
            for decap in (1, 0):
                lines = [f'* {m} {case}', f'.include {inc}', f'X1 bp bn pp pn vss vdd {sub}', 'Rbp bp 0 50', 'Rbn bn 0 50', 'Rpp pp 0 1e9', 'Rpn pn 0 1e9',
                         ('Cd vdd vd 5.4n\nRd vd vss 0.1' if decap else 'Rd vdd vss 1e9'), 'Iinj 0 vss AC 1', '.control']
                for i, f in enumerate(fs):
                    lines += [f'ac lin 1 {f} {f}', f'let z{i} = mag(v(vss))', f'let c{i} = db(mag(v(pp)-v(pn))/mag(v(vss)) + 1e-15)', f'print z{i} c{i}']
                lines += ['.endc', '.end']
                v = ng('\n'.join(lines) + '\n', f'chk_{m}_{case}_{decap}')
                res[f'{m}_{case}_decap{decap}'] = {f'{f / 1e6:g}MHz': dict(zvss_ohm=v.get(f'z{i}'), conv_db=v.get(f'c{i}')) for i, f in enumerate(fs)}
    # ground bonds near the RX pair: count and the parallel ground inductance seen by die VSS (all ground wires shorted together at die VSS)
    near = {}
    for case in ('min', 'nom', 'max'):
        L = lmat(case); ix = {k: i for i, k in enumerate(WEST)}
        for m, kinds in MAPS.items():
            g = [k for k in WEST if kinds[k] == 'gnd']; x = [k for k in WEST if kinds[k] == 'xgnd']
            idx = [ix[k] for k in g + x]; Lm = L[np.ix_(idx, idx)].copy()
            for a, k in enumerate(g + x):
                if k in x: Lm[a, a] += L_CAR[case]
            near[f'{m}_{case}'] = dict(west_ground_bonds=g, west_signal_site_grounds=x, within_3_sites_of_rx=[k for k in g + x if min(abs(k - P), abs(k - N)) <= 3],
                                      west_ground_parallel_nH=round(float(1 / np.linalg.inv(Lm).sum()), 4),
                                      bounce_conv_per_bond={k: round(float((L[ix[P], ix[k]] - L[ix[N], ix[k]]) / L[ix[k], ix[k]]), 4) for k in g + x})
    res['ground_bonds'] = near
    WORK.mkdir(parents=True, exist_ok=True); (WORK / 'check.json').write_text(json.dumps(res, indent=1)); print(json.dumps(res, indent=1))


if __name__ == '__main__':
    {'model': model, 'check': check}[sys.argv[1]]()
