"""Transistor-level source netlists for the RF transmit family.

One description drives both the schematic netlist (``<block>.spice``) and the
Magic layout generator (``layoutlib.py``), so LVS compares the layout against
exactly the devices simulated here. gf180mcuD devices only: 3.3 V
``nfet_03v3``/``pfet_03v3`` and unsilicided/silicided poly resistors.

Scope (consolidation pass item 1): ``txmix_i``/``txmix_q`` (upmixers with a
selectable filter-bypass DAC input), ``txsum`` (I/Q current summation and
load) and ``rfdriver`` (pre-amplifiers, programmable-current output stage and
the external-PA bypass switch). The TX reconstruction filter now lives in the
shared ``bbfilter_i/q`` owned by ``analog/rf_rx``.
"""
from dataclasses import dataclass, field

LOGIC_N = dict(w=1.0, l=0.28)
LOGIC_P = dict(w=2.0, l=0.28)


@dataclass
class Mos:
    name: str
    d: str
    g: str
    s: str
    b: str
    model: str
    w: float  # per-finger width, um
    l: float
    nf: int = 1

    @property
    def nodes(self):
        return (self.d, self.g, self.s, self.b)


@dataclass
class Res:
    name: str
    a: str
    b: str
    body: str
    model: str
    w: float
    l: float

    @property
    def nodes(self):
        return (self.a, self.b, self.body)


@dataclass
class Circuit:
    name: str
    ports: list
    devices: list = field(default_factory=list)
    notes: list = field(default_factory=list)

    # -- primitives -------------------------------------------------------
    def n(self, name, d, g, s, w, l, nf=1, b='VSS'):
        self.devices.append(Mos(name, d, g, s, b, 'nfet_03v3', w, l, nf))

    def p(self, name, d, g, s, w, l, nf=1, b='VDD'):
        self.devices.append(Mos(name, d, g, s, b, 'pfet_03v3', w, l, nf))

    def n6(self, name, d, g, s, w, l, nf=1, b='VSS'):
        self.devices.append(Mos(name, d, g, s, b, 'nfet_06v0', w, l, nf))

    def r(self, name, a, b, w, l, model='ppolyf_u_1k', body='VSS'):
        self.devices.append(Res(name, a, b, body, model, w, l))

    # -- static CMOS gates on the switched island rail ---------------------
    def inv(self, name, a, y):
        self.n(name + '_N', y, a, 'VSS', **LOGIC_N)
        self.p(name + '_P', y, a, 'VDD', **LOGIC_P)

    def nand2(self, name, a, b, y):
        self.n(name + '_NA', y, a, name + '_x', **LOGIC_N)
        self.n(name + '_NB', name + '_x', b, 'VSS', **LOGIC_N)
        self.p(name + '_PA', y, a, 'VDD', **LOGIC_P)
        self.p(name + '_PB', y, b, 'VDD', **LOGIC_P)

    def nor2(self, name, a, b, y):
        self.n(name + '_NA', y, a, 'VSS', **LOGIC_N)
        self.n(name + '_NB', y, b, 'VSS', **LOGIC_N)
        self.p(name + '_PA', name + '_x', a, 'VDD', **LOGIC_P)
        self.p(name + '_PB', y, b, name + '_x', **LOGIC_P)

    def nor3(self, name, a, b, c, y):
        self.n(name + '_NA', y, a, 'VSS', **LOGIC_N)
        self.n(name + '_NB', y, b, 'VSS', **LOGIC_N)
        self.n(name + '_NC', y, c, 'VSS', **LOGIC_N)
        self.p(name + '_PA', name + '_x', a, 'VDD', **LOGIC_P)
        self.p(name + '_PB', name + '_y', b, name + '_x', **LOGIC_P)
        self.p(name + '_PC', y, c, name + '_y', **LOGIC_P)

    # -- netlist -----------------------------------------------------------
    def nets(self):
        return sorted({n for d in self.devices for n in d.nodes})

    def spice_lines(self):
        out = []
        for d in self.devices:
            if isinstance(d, Mos):
                # One line per finger, matching the extracted multi-finger cell.
                for f in range(d.nf):
                    suffix = f'_f{f}' if d.nf > 1 else ''
                    # Junction geometry estimate (matches the PCell end-finger extraction:
                    # 0.44 um diffusion per side); LVS ignores these properties.
                    a, pr = d.w * 0.44, 2 * d.w + 0.88
                    out.append(f'X{d.name}{suffix} {d.d} {d.g} {d.s} {d.b} {d.model} '
                               f'w={d.w:g}u l={d.l:g}u ad={a:.4g}p as={a:.4g}p pd={pr:.4g}u ps={pr:.4g}u')
            else:
                out.append(f'X{d.name} {d.a} {d.b} {d.body} {d.model} '
                           f'r_width={d.w:g}u r_length={d.l:g}u')
        return out

    def spice(self):
        head = [f'* {self.name}: generated by analog/rf_tx/circuits.py', *[f'* {n}' for n in self.notes],
                f'.subckt {self.name} ' + ' '.join(self.ports)]
        return '\n'.join(head + self.spice_lines() + [f'.ends {self.name}', ''])

    def summary(self):
        mos = [d for d in self.devices if isinstance(d, Mos)]
        res = [d for d in self.devices if isinstance(d, Res)]
        return dict(devices=len(self.devices), mos_instances=len(mos), mos_fingers=sum(d.nf for d in mos),
                    resistors=len(res), nets=len(self.nets()))


# ---------------------------------------------------------------------------
# Design parameters (nominal tt/27C/3.3 V). Changing these changes the layout.
# ---------------------------------------------------------------------------
MIX = dict(
    gm_w=10.0, gm_nf=4, gm_l=0.28,          # input transconductor, per side
    quad_w=10.0, quad_nf=2, quad_l=0.28,     # commutating switches
    rdeg_w=4.0, rdeg_l=2.4,                  # differential degeneration (ppolyf_u_1k)
    sat_w=10.0, sat_nf=2,                    # degeneration short for the saturated mode
    tail_w=19.0, tail_nf=5, tail_l=1.0,      # per side, ~0.5 mA from the 10 uA diode (x47.5 nominal)
    diode_w=2.0, diode_l=1.0,
    sw_w=4.0, sw_l=0.28,                     # input-select NMOS switches
)
SUM = dict(
    rl_w=4.0, rl_l=3.6, rl_model='ppolyf_u',  # load per side, ~0.35 kohm/sq unsalicided
    hdr_w=20.0, hdr_nf=4,                     # PMOS header shared by both loads
    riso_w=2.0, riso_l=2.5,                   # I/Q port separation (silicided, ~9 ohm tt; 1..15 ohm/sq spread)
)
DRV = dict(
    diode_w=1.0, diode_l=0.5,                 # 10 uA reference diode
    unit_w=20.0, unit_l=0.5,                  # tail unit finger (~20x diode)
    pre1_w=10.0, pre1_nf=6, pre1_tail_nf=14, pre1_rl_w=2.0, pre1_rl_l=2.4,
    pre2_w=10.0, pre2_nf=6, pre2_tail_nf=14, pre2_rl_w=2.0, pre2_rl_l=2.2,
    pre3_w=10.0, pre3_nf=6, pre3_tail_nf=14, pre3_rl_w=2.0, pre3_rl_l=2.2,
    n_pre=3,                                  # three pre-amplifiers: the summed_rf level (~0.2 V pk diff at
                                              # full scale) must reach ~0.6 V to drive the output stage to Psat
    sf_w=10.0, sf_nf=12, sf_tail_nf=36,       # source followers p2 -> p3 (per side), drive the output gates
    out_w=20.0, out_nf=32, out_l=0.28,
    out_tail_nf=(12, 24, 48, 96),             # binary slices (fingers of unit_w/unit_l), ~36 mA at code 15
    ro_w=10.0, ro_l=44.0, ro_par=1,           # ~1.6 kohm ppolyf_u keeper per leg (header on). The output is
                                              # DC-fed by the board (balun centre tap / chokes to the island
                                              # rail); the old 4 x 400 ohm resistive feed dropped ~1.3 V and
                                              # took half the signal current (Psat ~+1 dBm).
    hdr_w=20.0, hdr_nf=48,                    # output-load PMOS header
    byp_w=20.0, byp_nf=2,                     # external-PA bypass PMOS per leg
    clamp_w=1.0, clamp_l=2.0,
    cas=True,                                 # RC-3: nfet_06v0 cascode between the output pair and the pads.
    cas_w=20.0, cas_nf=48, cas_l=0.7,         # 960/0.7 per leg; gate ~VDD (AC-grounded by a MOS cap): the
                                              # nfet_03v3 pair stays <= ~2.5 V Vds while the pad peaks 4.1-4.4 V
    casdc_w=10.0, casdc_l=4.0, casdc_nf=4,    # cascode-gate MOS decap per leg (~0.8 pF)
    se_w=20.0, se_nf=4,                       # D-TX-2: SE mode (se=1) turns the pad_n cascode off and steers that
                                              # leg's current into an on-chip PMOS dummy load (80/0.28, ~25 ohm)
    pad_clamp=False,                          # off-state pad pull-downs removed: with the board DC feed they
                                              # sank ~0.28 mA from the rail in reset; pads now rest at the feed
)
ATB_R = dict(w=1.0, l=20.0)                   # ~20 kohm isolation in every ATB tap


def txmix(name='pt_txmix_i'):
    c = Circuit(name, ['VDD', 'VSS', 'bb_p', 'bb_n', 'dac_p', 'dac_n', 'lo_p', 'lo_n',
                       'out_p', 'out_n', 'ibias', 'en', 'sel_dac', 'sat', 'atb_bias', 'atb_tail'])
    c.notes += ['Double-balanced Gilbert upmixer, NMOS degenerated transconductor, open-drain current outputs.',
                'Inputs: bb_* from bbfilter TX output (sel_dac=0) or dac_* direct DAC output (sel_dac=1).',
                'LO: DC-coupled rail-to-rail CMOS differential square wave on lo_p/lo_n.']
    m = MIX
    c.inv('IEN', 'en', 'enb')
    c.inv('ISEL', 'sel_dac', 'selb')
    c.nand2('GD', 'en', 'sel_dac', 'nd_dac')
    c.inv('ID', 'nd_dac', 's_dac')
    c.nand2('GB', 'en', 'selb', 'nd_bb')
    c.inv('IB', 'nd_bb', 's_bb')
    for leg in 'pn':
        c.n(f'SWB_{leg}', f'g_{leg}', 's_bb', f'bb_{leg}', m['sw_w'], m['sw_l'])
        c.n(f'SWD_{leg}', f'g_{leg}', 's_dac', f'dac_{leg}', m['sw_w'], m['sw_l'])
        c.n(f'CLG_{leg}', f'g_{leg}', 'enb', 'VSS', 1.0, 0.28)
        c.n(f'GM_{leg}', f'd_{leg}', f'g_{leg}', f'src_{leg}', m['gm_w'], m['gm_l'], m['gm_nf'])
        c.n(f'TAIL_{leg}', f'src_{leg}', 'vbt', 'VSS', m['tail_w'], m['tail_l'], m['tail_nf'])
    c.r('RDEG', 'src_p', 'src_n', m['rdeg_w'], m['rdeg_l'])
    # Saturated (constant-envelope) mode: sat=1 shorts the degeneration so the transconductor
    # commutates its full tail current and the driver chain is driven into limiting.
    c.nand2('GSAT', 'en', 'sat', 'nsat')
    c.inv('ISAT', 'nsat', 's_sat')
    c.n('SATSW', 'src_p', 's_sat', 'src_n', m['sat_w'], 0.28, m['sat_nf'])
    # Commutator: out_p collects d_p while lo_p is high and d_n while lo_n is high.
    c.n('QA', 'out_p', 'lo_p', 'd_p', m['quad_w'], m['quad_l'], m['quad_nf'])
    c.n('QB', 'out_n', 'lo_n', 'd_p', m['quad_w'], m['quad_l'], m['quad_nf'])
    c.n('QC', 'out_p', 'lo_n', 'd_n', m['quad_w'], m['quad_l'], m['quad_nf'])
    c.n('QD', 'out_n', 'lo_p', 'd_n', m['quad_w'], m['quad_l'], m['quad_nf'])
    # Bias: the 10 uA diode always sinks ibias; mirror gates switch to it only when enabled.
    c.n('DIODE', 'ibias', 'ibias', 'VSS', m['diode_w'], m['diode_l'])
    c.n('BSW', 'vbt', 'en', 'ibias', 2.0, 0.28)
    c.n('BPD', 'vbt', 'enb', 'VSS', 1.0, 0.28)
    c.r('RATB_B', 'vbt', 'atb_bias', **ATB_R)
    c.r('RATB_T', 'src_p', 'atb_tail', **ATB_R)
    return c


def txsum(name='pt_txsum'):
    c = Circuit(name, ['VDD', 'VSS', 'i_p', 'i_n', 'q_p', 'q_n', 'out_p', 'out_n', 'en', 'atb_cm'])
    c.notes += ['Current-summing load: I and Q mixer drains join at out_p/out_n through ~9 ohm silicided links;',
                'resistive loads to a PMOS header that opens when en=0; outputs clamped to VSS when disabled.']
    s = SUM
    c.inv('IEN', 'en', 'enb')
    c.p('HDR', 'hsum', 'enb', 'VDD', s['hdr_w'], 0.28, s['hdr_nf'])
    for leg in 'pn':
        c.r(f'RI_{leg}', f'i_{leg}', f'out_{leg}', s['riso_w'], s['riso_l'], model='ppolyf_s')
        c.r(f'RQ_{leg}', f'q_{leg}', f'out_{leg}', s['riso_w'], s['riso_l'], model='ppolyf_s')
        c.r(f'RL_{leg}', 'hsum', f'out_{leg}', s['rl_w'], s['rl_l'], model=s['rl_model'])
        c.n(f'CL_{leg}', f'out_{leg}', 'enb', 'VSS', 1.0, 0.28)
        c.r(f'RATB_{leg}', f'out_{leg}', 'atb_cm', **ATB_R)
    return c


def rfdriver(name='pt_rfdriver'):
    c = Circuit(name, ['VDD', 'VSS', 'in_p', 'in_n', 'pad_p', 'pad_n', 'ibias', 'en', 'mute', 'bypass',
                       'g0', 'g1', 'g2', 'g3', 'se', 'atb_bias', 'atb_pre', 'atb_cm'])
    c.notes += ['Two resistively loaded pre-amplifiers, NMOS source followers and a differential output pair with four binary',
                'switched tail slices (g3..g0 = rfdriver.gain code[7:4]); ~20 ohm/leg source resistors behind',
                'a PMOS header. bypass=1 turns the header and all tails off and connects in_* to pad_* through',
                'PMOS switches (debug.rf_tx_bypass, external-PA fallback).']
    d = DRV
    c.inv('IEN', 'en', 'enb')
    c.nor2('GPRE', 'enb', 'bypass', 'pre_on')
    c.inv('IPRE', 'pre_on', 'pre_off')
    c.nor3('GACT', 'enb', 'mute', 'bypass', 'act')
    c.inv('IBYP', 'bypass', 'byp_b')
    c.nor2('GOFF', 'en', 'bypass', 'off_all')
    # Bias line
    c.n('DIODE', 'ibias', 'ibias', 'VSS', d['diode_w'], d['diode_l'])
    c.n('BSW', 'vb', 'en', 'ibias', 2.0, 0.28)
    c.n('BPD', 'vb', 'enb', 'VSS', 1.0, 0.28)
    c.n('BCAP', 'VSS', 'vb', 'VSS', 10.0, 4.0, 2)
    c.n('PSW', 'vbp', 'pre_on', 'vb', 2.0, 0.28)
    c.n('PPD', 'vbp', 'pre_off', 'VSS', 1.0, 0.28)
    # Pre-amplifiers: in -> p1 [-> p1b] -> p2 (non-inverting naming; the last stage always drives p2)
    chain = [(1, 'in', 'p1'), (2, 'p1', 'p2')] if d.get('n_pre', 2) == 2 else \
        [(1, 'in', 'p1'), (2, 'p1', 'p1b'), (3, 'p1b', 'p2')]
    for stage, src, dst in chain:
        w, nf = d[f'pre{stage}_w'], d[f'pre{stage}_nf']
        c.n(f'A{stage}_P', f'{dst}_n', f'{src}_p', f't{stage}', w, 0.28, nf)
        c.n(f'A{stage}_N', f'{dst}_p', f'{src}_n', f't{stage}', w, 0.28, nf)
        c.n(f'T{stage}', f't{stage}', 'vbp', 'VSS', d['unit_w'], d['unit_l'], d[f'pre{stage}_tail_nf'])
        for leg in 'pn':
            c.r(f'R{stage}_{leg}', 'VDD', f'{dst}_{leg}', d[f'pre{stage}_rl_w'], d[f'pre{stage}_rl_l'], model='ppolyf_u')
    # Source followers isolate the output-pair gate capacitance from pre-amplifier 2.
    gate = 'p2'
    if d['sf_nf']:
        for leg in 'pn':
            c.n(f'SF_{leg}', 'VDD', f'p2_{leg}', f'p3_{leg}', d['sf_w'], 0.28, d['sf_nf'])
            c.n(f'TS_{leg}', f'p3_{leg}', 'vbp', 'VSS', d['unit_w'], d['unit_l'], d['sf_tail_nf'])
        gate = 'p3'
    # Output pair: pad_p follows p2_p. With the cascode the pair drains are cp/cn (inside the block).
    dp, dn = ('cp', 'cn') if d.get('cas') else ('pad_p', 'pad_n')
    c.n('O_P', dn, f'{gate}_p', 'to', d['out_w'], d['out_l'], d['out_nf'])
    c.n('O_N', dp, f'{gate}_n', 'to', d['out_w'], d['out_l'], d['out_nf'])
    if d.get('cas'):
        # nfet_06v0 cascodes (drains on the pads). Gates: vcp from a tie-high inverter, vcn = se_b, both
        # MOS-cap decoupled. Unpowered: gates at 0 V, so pad stress lands on the 6 V devices only.
        c.inv('ISE', 'se', 'se_b')
        c.inv('IHI', 'VSS', 'vcp')
        c.n6('CAS_P', 'pad_p', 'vcp', 'cp', d['cas_w'], d['cas_l'], d['cas_nf'])
        c.n6('CAS_N', 'pad_n', 'se_b', 'cn', d['cas_w'], d['cas_l'], d['cas_nf'])
        c.n('CDC_P', 'VSS', 'vcp', 'VSS', d['casdc_w'], d['casdc_l'], d['casdc_nf'])
        c.n('CDC_N', 'VSS', 'se_b', 'VSS', d['casdc_w'], d['casdc_l'], d['casdc_nf'])
        # SE dummy loads (pad_n leg on in SE; the pad_p twin is always off, for symmetry)
        c.p('DUM_P', 'cp', 'VDD', 'VDD', d['se_w'], 0.28, d['se_nf'])
        c.p('DUM_N', 'cn', 'se_b', 'VDD', d['se_w'], 0.28, d['se_nf'])
    for k, nf in enumerate(d['out_tail_nf']):
        c.nand2(f'GS{k}', 'act', f'g{k}', f'sk{k}_b')
        c.inv(f'IS{k}', f'sk{k}_b', f'sk{k}')
        c.n(f'SON{k}', f'vbo{k}', f'sk{k}', 'vb', 2.0, 0.28)
        c.n(f'SOF{k}', f'vbo{k}', f'sk{k}_b', 'VSS', 1.0, 0.28)
        c.n(f'TO{k}', 'to', f'vbo{k}', 'VSS', d['unit_w'], d['unit_l'], nf)
    # Output source resistors behind a header that is on only in normal drive.
    c.p('HDR', 'hdrv', 'pre_off', 'VDD', d['hdr_w'], 0.28, d['hdr_nf'])
    for leg in 'pn':
        for i in range(d['ro_par']):
            c.r(f'RO_{leg}{i}', 'hdrv', f'pad_{leg}', d['ro_w'], d['ro_l'], model='ppolyf_u')
        c.p(f'BYP_{leg}', f'pad_{leg}', 'byp_b', f'in_{leg}', d['byp_w'], 0.28, d['byp_nf'])
        if d.get('pad_clamp', True):
            c.n(f'CLP_{leg}', f'pad_{leg}', 'off_all', 'VSS', d['clamp_w'], d['clamp_l'])
        c.r(f'RATBC_{leg}', f'pad_{leg}', 'atb_cm', **ATB_R)
        c.r(f'RATBP_{leg}', f'p2_{leg}', 'atb_pre', **ATB_R)
    c.r('RATB_B', 'vb', 'atb_bias', **ATB_R)
    return c


BLOCKS = {
    'txmix_i': lambda: txmix('pt_txmix_i'),
    'txmix_q': lambda: txmix('pt_txmix_q'),
    'txsum': txsum,
    'rfdriver': rfdriver,
}

if __name__ == '__main__':
    import argparse, pathlib
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', type=pathlib.Path, default=pathlib.Path(__file__).parent)
    a = ap.parse_args()
    for blk, fn in BLOCKS.items():
        c = fn()
        (a.out / f'{blk}.spice').write_text(c.spice())
        print(blk, c.summary())
