"""QVCO layout (r4, LO owner 2026-11-11): pt_lc_qvco active core with the timing layout engine
(MIM caps and n-well varactors as PDK PCells, layout_engine CAP_PCELL), plus a top-level assembly
with the two drawn spirals (generated/lcvco/pt_spiral_ind).

Layout netlist (`qvco_layout.spice`, generated here from the qvco.spice r3 values; LVS reference):
  * same circuit as qvco.spice with physical regrouping only (same total W per function):
    NMOS pair 4 x 20 um -> 16 x 5 um; coupling 24 um -> 5 x 4.8 um; PMOS 6 x 20 um -> 24 x 5 um;
    tail 120 x 10/1 -> 24 x 50/1; band switches 6 um x m -> 12 um x m/2.
    5 um fingers contacted on one side = the README's conservative gate-R case (rgf = 51 ohm).
  * varactor pt_lc_var (behavioural, AREA 169 um^2) -> 4 x cap_nmos_03v3_b 21.15 x 2 um (169.2 um^2).
  * the spirals (XL) are not in the core: tank ports IP/IN (core I) and QP/QN (core Q) go to the
    assembly, where pt_spiral_ind connects them (an inductor shorts its two terminals for LVS, so the
    assembly is DRC-checked and the core is LVS-checked).
  * schematic gate resistors (RG*) are model elements; the extracted sim re-inserts the physical gate R.

    python3 qvco_layout.py core       # core layout, Magic DRC, LVS, KLayout DRC -> generated/lcvco/
    python3 qvco_layout.py assembly   # core + 2 spirals, Magic + KLayout DRC
"""
