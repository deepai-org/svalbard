def rows_for(devices):
    """Floorplan, bottom -> top.  The tank ports leave at the top edge (engine port trunks) to the
    spirals above, so the rows carrying the circulating tank current (fixed MIM + varactors, band MIMs,
    then the cross-coupled pairs) are nearest the top and the tank trunks are short there; tails and
    bias/PRE (no tank current) are at the bottom.  I and Q rows are interleaved so both cores see the
    same trunk geometry (systematic I/Q parasitic difference = one row pitch)."""
    names = [d.name for d in devices]
    by = lambda pre: [n for n in names if n.startswith(pre)]
    r = {}
    for c in ('CI', 'CQ'):
        p = c + '_'
        r[c, 'T'] = by(p + 'T_')
        r[c, 'N'] = by(p + 'N1_') + by(p + 'C1_') + by(p + 'C2_') + by(p + 'N2_')
        pp = by(p + 'P1_') + by(p + 'P2_')
        r[c, 'Pa'] = [n for k, n in enumerate(pp) if k % 2 == 0]   # P1/P2 alternate halves: both rows carry both sides
        r[c, 'Pb'] = [n for k, n in enumerate(pp) if k % 2 == 1]
        r[c, 'K'] = [p + 'CF'] + by(p + 'V1_') + by(p + 'V2_')
        sc = [n for k in range(4) for n in by(f'{p}S{k}_C')]
        r[c, 'SC'] = sc
        r[c, 'SW'] = [n for k in range(4) for n in by(f'{p}S{k}_') if n not in sc]
    order = ['T', 'N', 'Pa', 'Pb', 'SW', 'SC', 'K']
    rows = [r[c, k] for k in order for c in ('CI', 'CQ')]
    used = {n for row in rows for n in row}
    rows.insert(2, [n for n in names if n not in used])
    return [x for x in rows if x]


def core(wcf=WCF, tag=''):
    work = WORK / ('core' + tag)
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    src = work / 'qvco_layout.spice'
    src.write_text(layout_netlist(wcf))
    ports, devices = netlist.load(src, CELL)
    rows = rows_for(devices)
    wide = {n: 3.0 for n in ('IP', 'IN', 'QP', 'QN')}
    wide.update(TSI=2.0, TSQ=2.0)
    # bias / tuning nets kept a free trunk column away from the tank trunks (coupling into the mirror gate and VTUNE)
    # I and Q tank trunks pinned as two mirrored pairs 4.8 um apart (symmetric differential C), the pairs
    # 14.4 um apart (r4 v1 let IN sit beside QP: 77 fF I-Q coupling, QP-QN 181 vs IP-IN 110 fF -> Q-I -70 deg)
    rep = le.generate(work, CELL, ports, devices, rows=rows, net_width=wide, net_space={'IBIAS': 0.6, 'VTUNE': 0.6},
                      trunk_groups=[['IP', 'IN', None, None, 'QN', 'QP']])
    (work / 'schematic.spice').write_text(tf.with_antenna_diodes(netlist.flat_spice(ports, devices, CELL), rep))
    lvs = le.netgen_lvs(work, f'{CELL}.lvs.spice', CELL, 'schematic.spice', CELL)
    tf.gds_export_analog(work, CELL)
    kl = tf.klayout_drc(work, CELL)
    out = dict(cell=CELL, wcf_um=wcf, devices=len(devices), size_um=rep['size_um'], area_um2=rep['area_um2'],
               magic_drc=rep['drc_count_raw'], lvs=lvs, klayout=kl, antenna_diodes=len(rep['antenna_diodes']),
               work=str(work))
    (work / 'result.json').write_text(json.dumps(out, indent=1, default=str) + '\n')
    print(json.dumps(out, indent=1, default=str))
    return out


def publish(tag=''):
    work = WORK / ('core' + tag)
    GEN.mkdir(exist_ok=True)
    for suf in ('.mag', '.ext.spice', '.lvs.spice'):
        shutil.copy(work / f'{CELL}{suf}', GEN / f'{CELL}{suf}')
    shutil.copy(work / f'{CELL}.a.gds' if (work / f'{CELL}.a.gds').exists() else work / f'{CELL}.gds', GEN / f'{CELL}.gds')
    shutil.copy(work / 'lvs.txt', GEN / f'{CELL}-lvs.txt')
    shutil.copy(work / 'qvco_layout.spice', HERE / 'qvco_layout.spice')
    shutil.copy(work / 'result.json', GEN / f'{CELL}-layout.json')


def assembly(tag=''):
    """Top cell pt_lc_qvco_lay: the core + two pt_spiral_ind above it (Q mirrored), fed by 3-5 um Metal5
    lines from the core's tank port trunks (top edge).  DRC only (an inductor shorts its terminals for
    LVS); the core is the LVS-checked cell.  Feed geometry (no crossings): IP -> spiral I outer terminal A
    on the y=+29 um level, IN -> spiral I centre terminal B on the y=+44 um level; Q mirrored."""
    import re as _re
    work = WORK / ('asm' + tag)
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    core_dir = WORK / ('core' + tag)
    for f in core_dir.glob('*.mag'):
        shutil.copy(f, work / f.name)
    shutil.copy(GEN / 'pt_spiral_ind.mag', work / 'pt_spiral_ind.mag')
    mag = (work / f'{CELL}.mag').read_text()
    lab = {m.group(5): (int(m.group(1)) + int(m.group(3))) / 2 * 0.005
           for m in _re.finditer(r'flabel metal5 (-?\d+) (-?\d+) (-?\d+) (-?\d+) \d+ FreeSans \d+ 0 0 0 (\S+)', mag)}
    top = max(int(m.group(1)) for m in _re.finditer(r'flabel metal5 -?\d+ -?\d+ -?\d+ (-?\d+)', mag)) * 0.005
    # spiral terminals (um, cell coordinates): A (-157.5, -137.5) outer, B (0, -170) centre; bbox x -180..160, y -186..160
    ys = top + 50 + 186
    xi = lab['IP'] - 200
    xq = lab['QN'] + 200
    cmds = ['crashbackups stop', 'load pt_lc_qvco_lay', 'units microns', 'snap internal',
            f'getcell {CELL} child 0 0 parent 0 0',
            f'getcell pt_spiral_ind child 0 0 parent {xi} {ys}',
            f'getcell pt_spiral_ind h child 0 0 parent {xq} {ys}']
    def r(x1, y1, x2, y2):
        x1, x2 = sorted((x1, x2)); y1, y2 = sorted((y1, y2))
        cmds.extend([f'box values {x1:.3f} {y1:.3f} {x2:.3f} {y2:.3f}', 'paint metal5'])
        y2c = min(y2, ys - 190)             # Metal4 / via4 stop below the spiral cells (no contact overlap with them)
        if min(x2 - x1, y2c - y1) > 5:      # wide feed: Metal5 || Metal4 with a via4 field (risers stay Metal5 only)
            cmds.extend([f'box values {x1:.3f} {y1:.3f} {x2:.3f} {y2c:.3f}', 'paint metal4',
                         f'box values {x1 + 0.5:.3f} {y1 + 0.5:.3f} {x2 - 0.5:.3f} {y2c - 0.5:.3f}', 'paint via4'])
    yl, yh = top + 29, top + 52
    w, W = 1.5, 10.0    # 3 um risers from the 4.8 um-pitch port trunks, then 20 um Metal5||Metal4 feeds
    # I: IP -> A_I (xi-157.5), IN -> B_I (xi)
    r(lab['IP'] - w, top - 1, lab['IP'] + w, yl + W)
    r(xi - 157.5 - W, yl - W, lab['IP'] + w, yl + W)
    r(xi - 157.5 - W, yl - W, xi - 157.5 + W, ys - 137.5)
    r(lab['IN'] - w, top - 1, lab['IN'] + w, yh + W)
    r(xi - W, yh - W, lab['IN'] + w, yh + W)
    r(xi - W, yh - W, xi + W, ys - 170)
    # Q (mirrored spiral: A at xq + 157.5): QN -> A_Q, QP -> B_Q
    r(lab['QN'] - w, top - 1, lab['QN'] + w, yl + W)
    r(lab['QN'] - w, yl - W, xq + 157.5 + W, yl + W)
    r(xq + 157.5 - W, yl - W, xq + 157.5 + W, ys - 137.5)
    r(lab['QP'] - w, top - 1, lab['QP'] + w, yh + W)
    r(lab['QP'] - w, yh - W, xq + W, yh + W)
    r(xq - W, yh - W, xq + W, ys - 170)
    cmds += ['save pt_lc_qvco_lay', 'quit -noprompt']
    (work / 'asm.tcl').write_text('\n'.join(cmds) + '\n')
    le.docker_magic(work, 'asm.tcl')
    chk = ['crashbackups stop', 'load pt_lc_qvco_lay', 'select top cell', 'drc euclidean on', 'drc style drc(full)',
           'drc check', 'drc catchup', 'set f [open drc-count.txt w]', 'puts $f [drc list count total]',
           'puts $f [drc listall why]', 'close $f', 'gds write pt_lc_qvco_lay.gds', 'quit -noprompt']
    (work / 'drc.tcl').write_text('\n'.join(chk) + '\n')
    le.docker_magic(work, 'drc.tcl')
    tf.gds_export_analog(work, 'pt_lc_qvco_lay')
    kl = tf.klayout_drc(work, 'pt_lc_qvco_lay')
    drc = (work / 'drc-count.txt').read_text()
    feed = dict(IP_um=(lab['IP'] - (xi - 157.5)) + (yl - top) + (ys - 137.5 - yl), IN_um=(lab['IN'] - xi) + (yh - top) + (ys - 170 - yh))
    # feed series R / C estimates (Metal5 0.040 ohm/sq; area C to substrate ~0.008 fF/um^2 + fringe ~0.04 fF/um/edge)
    def seg(lst):
        # (length, width, sheet ohm/sq, area cap fF/um^2): M5 riser 0.040; M5||M4 feed 0.040||0.090 = 0.028, M4 area ~0.015
        return sum(l / wd * rs for l, wd, rs, ca in lst), sum(l * wd * ca + 2 * l * 0.04 for l, wd, rs, ca in lst)
    ip = seg([(yl - top, 3, 0.040, 0.008), (lab['IP'] - (xi - 157.5), 20, 0.028, 0.015), (ys - 137.5 - yl, 20, 0.028, 0.015)])
    inn = seg([(yh - top, 3, 0.040, 0.008), (lab['IN'] - xi, 20, 0.028, 0.015), (ys - 170 - yh, 20, 0.028, 0.015)])
    feed_rc = dict(IP_r_ohm=ip[0], IP_c_ff=ip[1], IN_r_ohm=inn[0], IN_c_ff=inn[1])
    out = dict(cell='pt_lc_qvco_lay', feed_rc_estimate=feed_rc, magic_drc=drc.split()[0] if drc.split() else drc, magic_details=drc[:600], klayout=kl,
               spiral_origin_um=dict(I=[xi, ys], Q=[xq, ys]), feed_length_um=feed,
               bbox_um=[xi - 180, 0, xq + 180, ys + 160], area_mm2=(xq - xi + 360) * (ys + 160) / 1e6)
    (work / 'result.json').write_text(json.dumps(out, indent=1, default=str) + '\n')
    print(json.dumps(out, indent=1, default=str))
    return out


