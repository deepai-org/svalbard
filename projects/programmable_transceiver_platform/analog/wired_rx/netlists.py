def termination():
    c = Net('pt_termination',
            ['VDD_WIRE_SW', 'VSS', 'term_en', 'term_mode0', 'term_mode1',
             'TERM_ENABLE', 'DIFF_ENABLE', 'TERM_VCM'],
            """Control and common-mode source for the pad-resident RX termination bank
(analog/pads wired_receive: 24 ohm + 8x20um shunt switches per leg, 5x20um bridge).
term_mode[1:0]: 00 off | 01 shunt to TERM_VCM=1.2 V divider | 10 100 ohm differential bridge
| 11 shunt to TERM_VCM=VSS (USB HS 45 ohm to ground). term_en=0 forces off.
TERM_VCM is grounded whenever the divider is not selected (incl. off), bleed 50k when unpowered.""")
    c.vdd = 'VDD_WIRE_SW'
    c.inv('term_mode0', 'm0b'); c.inv('term_mode1', 'm1b')
    # TERM_ENABLE = en & mode0
    c.nand(['term_en', 'term_mode0'], 'te_b'); c.inv('te_b', 'TERM_ENABLE', wn=2, wp=4)
    # DIFF_ENABLE = en & mode1 & !mode0
    c.nand(['term_en', 'term_mode1', 'm0b'], 'de_b'); c.inv('de_b', 'DIFF_ENABLE', wn=2, wp=4)
    # Divider on = en & mode0 & !mode1
    c.nand(['term_en', 'term_mode0', 'm1b'], 'dv_b'); c.inv('dv_b', 'dv', wn=2, wp=4)
    c.p('vtop', 'dv_b', 'VDD_WIRE_SW', w=20)          # top switch
    c.r('vtop', 'TERM_VCM', 2, 3.5)                  # 1.75k
    c.r('TERM_VCM', 'vbot', 2, 2)                    # 1.0k
    c.n('vbot', 'dv', 'VSS', w=10)                   # bottom switch
    # Ground switch: on whenever divider is off (USB HS, diff, off)
    c.n('TERM_VCM', 'dv_b', 'VSS', w=20, m=40)
    # Decoupling on TERM_VCM (~1.8 pF) and unpowered bleed
    c.ncap('TERM_VCM', 20, 5, m=4)
    c.r('TERM_VCM', 'vbl1', 1, 25); c.r('vbl1', 'VSS', 1, 25)
    return c


def rxlevel():
    c = Net('pt_rxlevel', ['VDD_WIRE_SW', 'VSS', 'rxlevel_en', 'rxlevel_half', 'DIV_ENABLE', 'BYPASS_ENABLE'],
            """Control for the pad-resident rxlevel network (analog/pads wired_receive: 2k/2k divider
with DIV_ENABLE ground + DIV_SELECT 6V NMOS, 4x20um 6V BYPASS NMOS per leg).
rxlevel_en=0: both off (RX_P/N high-Z from pad). half=0: bypass. half=1: divide-by-two.
Break-before-make: each output is qualified by the delayed complement of the other.
Outputs have 100k poly bleeds to VSS so the pad switches stay off when unpowered.""")
    c.vdd = 'VDD_WIRE_SW'
    c.inv('rxlevel_half', 'hb')
    c.nand(['rxlevel_en', 'hb', 'divd_b'], 'byp_b'); c.inv('byp_b', 'BYPASS_ENABLE', wn=4, wp=8)
    c.nand(['rxlevel_en', 'rxlevel_half', 'bypd_b'], 'div_b'); c.inv('div_b', 'DIV_ENABLE', wn=4, wp=8)
    # delayed complements (3 slow inverters each)
    for src, dst in (('DIV_ENABLE', 'divd_b'), ('BYPASS_ENABLE', 'bypd_b')):
        prev = src
        for k in range(5):
            nxt = dst if k == 4 else f'{dst}_{k}'
            c.inv(prev, nxt, l=2.)
            prev = nxt
    for out in ('DIV_ENABLE', 'BYPASS_ENABLE'):
        prev = out
        for i in range(4):
            nxt = 'VSS' if i == 3 else f'{out}_bl{i}'
            c.r(prev, nxt, 1, 25)
            prev = nxt
    return c


def rxselect():
    c = Net('pt_rxselect', ['VDD_WIRE_SW', 'VSS', 'rxselect_en', 'rxselect_direct',
                            'CTLE_P', 'CTLE_N', 'RX_P', 'RX_N', 'SL_P', 'SL_N'],
            """2:1 differential transmission-gate mux feeding the slicer bank (SL_P/N).
direct=0: CTLE output (equalized serial). direct=1: RX_P/N straight from rxlevel (USB HS
0-0.4 V lines, or any route that must avoid the CTLE block entirely).
rxselect_en=0: both gates open and SL_P/N clamped to VSS.""")
    c.vdd = 'VDD_WIRE_SW'
    c.inv('rxselect_direct', 'db')
    c.nand(['rxselect_en', 'db'], 'sa_b'); c.inv('sa_b', 'sa', wn=2, wp=4)
    c.nand(['rxselect_en', 'rxselect_direct'], 'sb_b'); c.inv('sb_b', 'sb', wn=2, wp=4)
    c.inv('rxselect_en', 'enb')
    for leg in 'PN':
        c.tg(f'CTLE_{leg}', f'SL_{leg}', 'sa', 'sa_b', wn=10, wp=20)
        c.tg(f'RX_{leg}', f'SL_{leg}', 'sb', 'sb_b', wn=10, wp=20)
        c.n(f'SL_{leg}', 'enb', 'VSS', w=2)
    return c


def wmon_sel():
    c = Net('pt_wmon_sel', ['VDD_WIRE_SW', 'VSS', 'wmon_en', 'wmon_sel0', 'wmon_sel1',
                            'RX_P', 'RX_N', 'CTLE_P', 'CTLE_N', 'WMON_IN'],
            """WMON source selector in front of the shared bb_tap observation buffer (rf_rx agent).
sel 00 RX_P | 01 RX_N (front end, before CTLE) | 10 CTLE_P | 11 CTLE_N. Independent of rxselect,
slicer and detect so the wire_wmon_scope / wire_detect_via_wmon routes share no failure with them.
wmon_en=0: all gates open, WMON_IN clamped to VSS.""")
    c.vdd = 'VDD_WIRE_SW'
    c.inv('wmon_sel0', 's0b'); c.inv('wmon_sel1', 's1b'); c.inv('wmon_en', 'enb')
    srcs = ['RX_P', 'RX_N', 'CTLE_P', 'CTLE_N']
    for i, src in enumerate(srcs):
        a = 'wmon_sel0' if i & 1 else 's0b'
        b = 'wmon_sel1' if i & 2 else 's1b'
        c.nand(['wmon_en', a, b], f'g{i}_b'); c.inv(f'g{i}_b', f'g{i}')
        c.tg(src, 'WMON_IN', f'g{i}', f'g{i}_b', wn=4, wp=8)
    c.n('WMON_IN', 'enb', 'VSS', w=1)
    return c


def ctle():
    c = Net('pt_ctle', ['VDD_WIRE_SW', 'VSS', 'IBIAS', 'ctle_en', 'wire_ctle_bypass', 'ctle_peak0', 'ctle_peak1',
                        'RX_P', 'RX_N', 'CTLE_P', 'CTLE_N', 'atb_ctle_pbias', 'atb_ctle_src'],
            """Source-degenerated PMOS-input CTLE (input CM 0.5-1.5 V, output CM ~1.0 V into slicer).
2 x 2.5 mA PMOS tails; degeneration Rs = 0.40/0.56/0.93/2.8 kohm (ctle_peak[1:0]=0..3) with ~0.4 pF per side;
400 ohm loads to VSS
through enable switches. IBIAS: 10 uA sunk from the island bias distribution.
wire_ctle_bypass=1: amplifier forced off, load switches open, transmission gates connect RX->CTLE.
Neither enable nor bypass: loads/clamps hold CTLE_P/N at VSS; no bias current.""")
    c.vdd = 'VDD_WIRE_SW'
    V = 'VDD_WIRE_SW'
    # control
    c.inv('wire_ctle_bypass', 'bypb')
    c.nand(['ctle_en', 'bypb'], 'ena_b'); c.inv('ena_b', 'ena', wn=2, wp=4)
    c.nor(['ena', 'wire_ctle_bypass'], 'clamp')
    c.inv('wire_ctle_bypass', 'byp_bb', wn=2, wp=4)    # byp_bb = !bypass  (TG pmos gate)
    c.inv('byp_bb', 'byp_q', wn=2, wp=4)               # buffered bypass (TG nmos gate)
    # branch switch gates (PMOS, on when low): on = ena & !peak  ->  gate = NAND(ena, !peak)
    c.inv('ctle_peak0', 'pk0i'); c.inv('ctle_peak1', 'pk1i')
    c.nand(['pk0i', 'ena'], 'pk0_n'); c.nand(['pk1i', 'ena'], 'pk1_n')
    # bias: IBIAS -> switch -> nmos diode; nmos mirror x2.5 -> pmos diode (atb_ctle_pbias)
    c.n('nbias', 'ena', 'IBIAS', w=4)
    c.n('nbias', 'nbias', 'VSS', w=2, l=1)
    c.n('nbias', 'ena_b', 'VSS', w=1)
    c.n('atb_ctle_pbias', 'nbias', 'VSS', w=5, l=1)
    c.p('atb_ctle_pbias', 'atb_ctle_pbias', V, w=2, l=.5)
    c.p('atb_ctle_pbias', 'ena', V, w=2)               # pull bias gate to VDD when off
    # tails (10 x 20/0.5 per side ~ ratio 100 -> 2.5 mA)
    c.p('sp', 'atb_ctle_pbias', V, w=20, l=.5, m=10)
    c.p('atb_ctle_src', 'atb_ctle_pbias', V, w=20, l=.5, m=10)
    # input pair, body tied to source
    # speed pass: 48 um input pair (was 80) to cut the RX_P load; loads raised to 480 ohm
    c.p('CTLE_N', 'RX_P', 'sp', b='sp', w=16, m=3)
    c.p('CTLE_P', 'RX_N', 'atb_ctle_src', b='atb_ctle_src', w=16, m=3)
    # degeneration: Rs = 2.8k || (pk0 ? open : 1.4k) || (pk1 ? open : 0.7k); fixed ~0.4 pF per side
    # code 00 -> 0.40k (least peaking, highest DC gain) ... 11 -> 2.8k (most peaking)
    c.r('sp', 'atb_ctle_src', 1, 2.8)
    c.r('sp', 'rsb', 2, 2.8); c.p('rsb', 'pk0_n', 'atb_ctle_src', b='VDD_WIRE_SW', w=20)
    c.r('sp', 'rsa', 2, 1.4); c.p('rsa', 'pk1_n', 'atb_ctle_src', b='VDD_WIRE_SW', w=20)
    for side in ('sp', 'atb_ctle_src'):
        c.ncap(side, 20, 4)
    # loads through enable switches
    for out in ('CTLE_P', 'CTLE_N'):
        c.r(out, f'{out}_rl', 5, 2.4)
        c.n(f'{out}_rl', 'ena', 'VSS', w=20)
        c.n(out, 'clamp', 'VSS', w=2)
    # bypass transmission gates
    c.tg('RX_P', 'CTLE_P', 'byp_q', 'byp_bb', wn=20, wp=20)
    c.tg('RX_N', 'CTLE_N', 'byp_q', 'byp_bb', wn=20, wp=20)
    return c


def _strongarm(c, tag, ck, inp, inn, outp_name, ref=None, trim=None, ckn_ext=None, tail_src=None):
    """PMOS-input StrongARM + NOR SR latch.  Evaluates while `ck` is high.

    outp_name goes high when inp < inn ... (polarity fixed below so that
    outp_name = 1 when v(inp) > v(inn)).  `ref`=(refp, refn) adds a second pair
    so the decision is (inp-inn) > (refp-refn).  `trim`: (tp0,tp1,tn0,tn1) bits.
    """
    V = c.vdd
    c.rowbreak()
    if ckn_ext is None:
        ckn = f'{tag}_ckn'
        c.nand([ck, c.en], ckn, wn=c.sa_k * 4, wp=c.sa_k * 8)
    else:
        # half-rate: the complementary clock is the tail/reset drive directly (no local
        # inversion delay); enable gating is the shared tail header `tail_src`
        ckn = ckn_ext
    # names sort as 1pa < 2oa < 3ob < 4pb so routing-track neighbours are symmetric
    x, pa, pb, oa, ob = (f'{tag}_{s}' for s in ('x', '1pa', '4pb', '2oa', '3ob'))
    c.p(x, ckn, tail_src or V, w=c.sa_k * 16)
    # Higher gate voltage -> less current.  inp on side a: if inp > inn, side b
    # integrates faster and ob rises first.
    c.p(pa, inp, x, w=c.sa_k * 12)
    c.p(pb, inn, x, w=c.sa_k * 12)
    if ref is not None:
        refp, refn = ref
        # side a also sees refn, side b sees refp: decision (inp-inn) vs (refp-refn)
        c.p(pa, refn, x, w=c.sa_k * 12)
        c.p(pb, refp, x, w=c.sa_k * 12)
    c.p(oa, ob, pa, w=c.sa_k * 8)
    c.p(ob, oa, pb, w=c.sa_k * 8)
    c.n(oa, ob, 'VSS', w=c.sa_k * 4)
    c.n(ob, oa, 'VSS', w=c.sa_k * 4)
    for node in (pa, pb, oa, ob):
        c.n(node, ckn, 'VSS', w=c.sa_rst)
    if trim is not None:
        tp0, tp1, tn0, tn1 = trim
        for node, b0, b1 in ((pa, tp0, tp1), (pb, tn0, tn1)):
            # switch-only trim: the switch connects its floating diffusion (~1-2 fF)
            # to the integrating node; a MOS-cap unit (~7 fF) moved the offset > 250 mV
            c.n(f'{tag}_9{node[-2:]}t0', b0, node, w=.5)
            c.n(f'{tag}_9{node[-2:]}t1', b1, node, w=1.)
    # NOR SR latch: ob high (inp>inn) sets q
    q, qb = f'{tag}_q', f'{tag}_qb'
    c.nor([oa, qb], q, wn=c.sa_latch, wp=2 * c.sa_latch)
    c.nor([ob, q], qb, wn=c.sa_latch, wp=2 * c.sa_latch)
    # gated output: out = q & en = NOR(qb, enb)
    if c.sa_buf:
        c.nor([qb, c.enb], f'{tag}_o1', wn=2, wp=4)
        c.inv(f'{tag}_o1', f'{tag}_o2', wn=2, wp=4)
        c.inv(f'{tag}_o2', outp_name, wn=4, wp=8)
    else:
        c.nor([qb, c.enb], outp_name, wn=2, wp=4)
    c.rowbreak()


def _ms_flop(c, tag, d, clk, clkb, vdd, vss):
    """Static transmission-gate master-slave flop, captures d on clk rising (clkb = !clk).
    Returns (s, sb) where sb = captured d and s = !d (both static).  Strong TGs/inverters with
    weak (0.5 um) keepers so the internal nodes swing fully at a 1.25 GHz clock."""
    m, mb, sl, sb = (f'{tag}_{x}' for x in ('m', 'mb', 's', 'sb'))
    c.tg(d, m, clkb, clk, wn=4, wp=8)                      # master transparent while clk low
    c.inv_r(m, mb, vdd, vss, wn=6, wp=12)
    c.tinv(mb, m, clk, clkb, wn=.5, wp=.5, vdd=vdd, vss=vss)  # weak master keeper (clk high)
    c.tg(mb, sl, clk, clkb, wn=6, wp=12)                   # slave transparent while clk high
    c.inv_r(sl, sb, vdd, vss, wn=4, wp=8)
    c.tinv(sb, sl, clkb, clk, wn=.5, wp=.5, vdd=vdd, vss=vss)  # weak slave keeper (clk low)
    return sl, sb


def slicer():
    ports = ['VDD_WIRE_SW', 'VSS', 'slicer_en', 'SL_P', 'SL_N'] + [f'CKP{k}' for k in range(8)] + ['QCK',
             'D0', 'E0', 'D1', 'E1', 'D2', 'E2', 'D3', 'E3']
    trims = []
    for s_ in ('d0', 'e0', 'd1', 'e1'):
        trims.append([f'trim_{s_}_{b}' for b in ('p0', 'p1', 'n0', 'n1')])
        ports += trims[-1]
    c = Net('pt_slicer', ports,
            """Quarter-rate sampler bank: eight PMOS-input StrongARM samplers on the eight 45-degree
quarter-rate clocks CKP0..CKP7 from pt_cdr (line_rate/4; 625 MHz at 2.5 Gb/s):
D0@CKP0, E0@CKP1, D1@CKP2, E1@CKP3, D2@CKP4, E2@CKP5, D3@CKP6, E3@CKP7 (E_i = edge after D_i).
Each sampler's tail/reset is driven by the opposite phase (CKP(k+4)), so it evaluates for half a
quarter-rate period (0.8 ns at 2.5 Gb/s); a NOR SR latch holds the decision for one period.
QCK = buffered CKP0 for the RTL (capture D0..E1 on QCK rising, D2..E3 on QCK falling).
Input CM 0..~1.5 V, so the same bank is the USB 2.0 HS receiver (CM ~0.2 V).
Offset trim: 2+2 bits of switched diffusion capacitance, shared by the two samplers of a phase.
slicer_en=0: shared tail header off, outputs forced low.""")
    c.vdd = 'VDD_WIRE_SW'
    c.en, c.enb = 'slicer_en', 'enb'
    c.sa_k, c.sa_rst, c.sa_latch, c.sa_buf = 2, 4, 2, True
    V = 'VDD_WIRE_SW'
    c.inv('slicer_en', 'enb')
    c.p('vdd_sa', 'enb', V, w=20, m=8)                  # sampler tail header
    c.nand(['CKP0', 'slicer_en'], 'qck_b', wn=2, wp=4)   # QCK held low (static) when disabled
    c.inv('qck_b', 'QCK', wn=4, wp=8)
    plan = [('sd0', 0, 'D0', 0), ('se0', 1, 'E0', 1), ('sd1', 2, 'D1', 2), ('se1', 3, 'E1', 3),
            ('sd2', 4, 'D2', 0), ('se2', 5, 'E2', 1), ('sd3', 6, 'D3', 2), ('se3', 7, 'E3', 3)]
    for tag, k, out, ti in plan:
        _strongarm(c, tag, None, 'SL_P', 'SL_N', out, trim=trims[ti], ckn_ext=f'CKP{(k + 4) % 8}', tail_src='vdd_sa')
    return c


def detect():
    c = Net('pt_detect', ['VDD_WIRE_SW', 'VSS', 'IBIAS', 'det_en', 'det_clk', 'RX_P', 'RX_N', 'TX_P', 'TX_N',
                          'det_thr0', 'det_thr1', 'det_se0', 'det_se1', 'det_src_tx', 'det_inject',
                          'DIFF_POS', 'DIFF_NEG', 'SE_P', 'SE_N', 'atb_det_vref'],
            """Clocked line sensor (samples on det_clk high).  Four PMOS-input StrongARM comparators:
DIFF_POS = (P-N) > Vthr, DIFF_NEG = (N-P) > Vthr  (squelch / disconnect / OOB idle envelope),
SE_P = P > Vse, SE_N = N > Vse (USB FS/LS single-ended receivers; SE0 = both low, in RTL).
P/N = RX_P/N (wire RX pair after the pad's rxlevel bypass/divider switches, so no PMOS
junction faces the bond pads), or TX_P/N when det_src_tx=1 (receiver detection on the TX pads;
NMOS-only pass and NMOS-switched injection so an unpowered island cannot be back-fed from TX pads).
Vthr (det_thr[1:0]): 0 / 62.5 / 125 / 670 mV nominal (extracted effective ~0 / 66 / 125 / ~555 mV).  Vse (det_se[1:0]): 0.8 / 1.125 / 1.4 / 2.0 V.
100 kohm-scale ladder 33 kohm total (100 uA).  det_inject=1 sources ~100 uA into each TX pad
(receiver-detect test current).  det_en=0: ladder, bias, comparators and injection off.""")
    V = 'VDD_WIRE_SW'
    c.vdd = V
    c.en, c.enb = 'det_en', 'enb'
    c.inv('det_en', 'enb'); c.inv('enb', 'enq', wn=2, wp=4)
    # ladder (100 uA): taps B=0.5, B1=0.5625, B2=0.625, S0=0.8, B3=1.125, S1=1.4, S2=2.0
    c.p('lad_top', 'enb', V, w=20)
    # B3 raised by ~45 mV (S1-B3 2.75k -> 2.3k, B3-S0 3.25k -> 3.7k) so the extracted USB disconnect
    # threshold (det_thr=3) lands inside 525-625 mV (was 506-516 mV)
    segs = [('lad_top', 'S2', 2, 26), ('S2', 'S1', 2, 12), ('S1', 'B3', 2, 4.6), ('B3', 'S0', 2, 7.4),
            ('S0', 'B2', 2, 3.5), ('B2', 'B1', 2, 1.25), ('B1', 'atb_det_vref', 2, 1.25),
            ('atb_det_vref', 'lad_bot', 2, 10)]
    for a, b, w, l in segs:
        c.r(a, b, w, l)
    c.n('lad_bot', 'enq', 'VSS', w=20)
    # threshold decode
    c.inv('det_thr0', 't0b'); c.inv('det_thr1', 't1b'); c.inv('det_se0', 'e0b'); c.inv('det_se1', 'e1b')
    for i, tap in enumerate(['atb_det_vref', 'B1', 'B2', 'B3']):
        a = 'det_thr0' if i & 1 else 't0b'
        b = 'det_thr1' if i & 2 else 't1b'
        c.nand([a, b], f'tg{i}_b'); c.inv(f'tg{i}_b', f'tg{i}')
        c.tg(tap, 'VTHP', f'tg{i}', f'tg{i}_b', wn=2, wp=4)
    for i, tap in enumerate(['S0', 'B3', 'S1', 'S2']):
        a = 'det_se0' if i & 1 else 'e0b'
        b = 'det_se1' if i & 2 else 'e1b'
        c.nand([a, b], f'sg{i}_b'); c.inv(f'sg{i}_b', f'sg{i}')
        c.tg(tap, 'VSE', f'sg{i}', f'sg{i}_b', wn=2, wp=4)
    # reference decoupling against comparator kick-back (~0.45 pF each)
    # refn reaches the comparators through an always-on copy of the threshold TG so both
    # reference gates see the same source impedance and kick-back recovery
    c.tg('atb_det_vref', 'VREFN', V, 'VSS', wn=2, wp=4)
    for node in ('VREFN', 'VTHP', 'VSE'):
        c.pcap(node, 20, 1, m=5)
    # source select
    c.inv('det_src_tx', 'srcb')
    c.nand(['det_en', 'srcb'], 'ln_b'); c.inv('ln_b', 'ln')
    c.nand(['det_en', 'det_src_tx'], 'tx_b'); c.inv('tx_b', 'tx')
    for leg in 'PN':
        c.tg(f'RX_{leg}', f'DP_{leg}', 'ln', 'ln_b', wn=2, wp=4)
        c.n(f'TX_{leg}', 'tx', f'DP_{leg}', w=4)
        c.n(f'DP_{leg}', 'enb', 'VSS', w=1)
    # comparators
    _strongarm(c, 'cdp', 'det_clk', 'DP_P', 'DP_N', 'DIFF_POS', ref=('VTHP', 'VREFN'))
    _strongarm(c, 'cdn', 'det_clk', 'DP_N', 'DP_P', 'DIFF_NEG', ref=('VTHP', 'VREFN'))
    _strongarm(c, 'csp', 'det_clk', 'DP_P', 'VSE', 'SE_P')
    _strongarm(c, 'csn', 'det_clk', 'DP_N', 'VSE', 'SE_N')
    # receiver-detect injection: IBIAS 10u -> nmos diode -> nmos x1 -> pmos diode -> pmos x10 per leg
    c.nand(['det_en', 'det_inject'], 'inj_b'); c.inv('inj_b', 'inj')
    c.n('dnb', 'enq', 'IBIAS', w=4)
    c.n('dnb', 'dnb', 'VSS', w=2, l=1)
    c.n('dnb', 'enb', 'VSS', w=1)
    c.n('dpb', 'dnb', 'VSS', w=2, l=1)
    c.p('dpb', 'dpb', V, w=2, l=1)
    c.p('dpb', 'enq', V, w=2)
    for leg in 'PN':
        c.p(f'inj_{leg}', 'dpb', V, w=20, l=1)
        c.n(f'TX_{leg}', 'inj', f'inj_{leg}', w=4)
    return c


def _aoi22(c, a, b, cc, d, y, vdd, vss, wn=2., wp=4.):
    """y = !((a & b) | (cc & d)) on explicit rails."""
    u = c._id(f'{y}_aoi')
    c.n(y, a, f'{u}n1', wn); c.n(f'{u}n1', b, vss, wn)
    c.n(y, cc, f'{u}n2', wn); c.n(f'{u}n2', d, vss, wn)
    c.p(f'{u}p', a, vdd, w=wp); c.p(f'{u}p', b, vdd, w=wp)
    c.p(y, cc, f'{u}p', w=wp); c.p(y, d, f'{u}p', w=wp)


def _nand4(c, ins, y, vdd, vss, wn=2., wp=2.):
    prev = vss
    for i, a in enumerate(ins):
        nxt = y if i == 3 else f'{y}_s{i}'
        c.n(nxt, a, prev, wn * 2)
        prev = nxt
    for a in ins:
        c.p(y, a, vdd, w=wp)


def _dff(c, d, ck, q):
    """Positive-edge D flip-flop from six NAND gates (no reset; q settles within two clock edges)."""
    t = q + '_'
    c.nand([t + '4', t + '2'], t + '1')
    c.nand([t + '1', ck], t + '2')
    c.nand([t + '2', ck, t + '4'], t + '3')
    c.nand([t + '3', d], t + '4')
    c.nand([t + '2', t + 'qb'], q)
    c.nand([q, t + '3'], t + 'qb')


def _long_stack(c, kind, d, g, s_, w, l_each, n, b=None):
    """n series devices of length l_each (one long-channel current source)."""
    prev = s_
    for i in range(n):
        nxt = d if i == n - 1 else f'{d}_ls{c._id("k")}'
        if kind == 'n':
            c.n(nxt, g, prev, w=w, l=l_each)
        else:
            c.p(nxt, g, prev, b=b, w=w, l=l_each)
        prev = nxt


def cdr():
    ports = ['VDD_PLL_SW', 'VSS', 'IBIAS', 'cdr_en', 'freq_hold', 'bb_gain', 'BB_UP', 'BB_DN', 'IB_PLL', 'VCTRL',
             'REF_IN', 'REF_PLL', 'FBCK_IN', 'atb_cdr_pbias']
    c = Net('pt_cdr', ports,
            """Dual-loop CDR analog cell (no phase interpolator).  Works with a second instance of the timing
family's pt_pll_ring (analog/timing/pll_ring.spice, instantiated unchanged at integration):
  * IB_PLL -> pt_pll_ring.IBIAS: 10 uA bias for the ring PLL's charge pump.  freq_hold=0: the PLL's
    PFD/charge pump lock the RX ring to the reference (frequency loop).  freq_hold=1 freezes it:
  * At the first FBCK_IN (<- pt_pll_ring.FBCK) falling edge after freq_hold, REF_IN -> REF_PLL
    (-> pt_pll_ring.REF) is held low and IB_PLL is clamped to VSS together, so the PLL's PFD parks
    (DN on) onto an already unbiased pump.  cdr_en=0 also clamps IB_PLL, holds REF_PLL low and stops
    the hand-over flops' clock.
  * VCTRL <-> pt_pll_ring.ATB_VCTRL (the loop-filter node): a weak bang-bang charge pump driven by
    BB_UP / BB_DN from pt_wrx_cdr_loop (one word period per decision) adds/removes ~60 nA
    (bb_gain=1: ~120 nA).  Through the PLL's 20 kohm series resistor this is the proportional path,
    the filter capacitors integrate it (phase loop with frequency tracking).
  * cdr_en=0: no current, IB_PLL clamped, BB pump switches open.
IBIAS: 10 uA sunk from the island bias distribution.""")
    V = 'VDD_PLL_SW'
    c.vdd = V
    c.inv('cdr_en', 'enb')
    c.inv('freq_hold', 'holdb')
    c.nand(['cdr_en', 'freq_hold'], 'holdon_b', wn=2, wp=4)  # low = ramp the PLL pump bias down
    c.inv('holdon_b', 'holdon', wn=1, wp=2)
    # Hand-over (extracted lessons): ramping the PLL pump bias while its PFD runs left the UP source
    # (slow PMOS mirror node) on longer than the DN sink (+1..3 % ring step); gating REF while the pump
    # is biased parked DN on a live 20 uA sink (VCTRL collapse; with the clamp one FBCK edge later
    # still ~130 fC = -2 %).  Now, at the first FBCK falling edge after freq_hold (mid-cycle: when
    # locked, REF and FB rise together half a period away), REF_PLL is held low AND IB_PLL is clamped
    # to VSS in the same instant.  The PFD is idle then; at the next FB edge it parks with DN on, onto
    # a sink that is already dead, and UP stays off.  Leaving hold restores both at a falling edge.
    c.nand(['FBCK_IN', 'cdr_en'], 'fbck_b', wn=1, wp=2)    # flops not clocked when disabled
    _dff(c, 'holdon', 'fbck_b', 'hq1')
    c.nand(['hq1', 'cdr_en'], 'gref_b', wn=2, wp=4)
    c.nand(['REF_IN', 'gref_b', 'cdr_en'], 'refg_b', wn=2, wp=8)   # REF_PLL low when disabled
    c.inv('refg_b', 'REF_PLL', wn=8, wp=8)    # stiff low: REF_IN feedthrough when off (85 C)
    c.nand(['cdr_en', 'gref_b'], 'ibclamp', wn=2, wp=4)     # high = IB_PLL source off and clamped
    c.nand(['cdr_en', 'freq_hold'], 'bbon_b', wn=2, wp=4)    # BB pump on = en & hold
    c.inv('bbon_b', 'bbon', wn=2, wp=4)
    # reference: IBIAS -> switch -> NMOS diode (4/2) -> PMOS diode (8/2, atb_cdr_pbias)
    c.n('nbd', 'cdr_en', 'IBIAS', w=4)
    c.n('nbd', 'nbd', 'VSS', w=4, l=2)
    c.n('nbd', 'enb', 'VSS', w=1)
    c.n('atb_cdr_pbias', 'nbd', 'VSS', w=4, l=2)
    c.p('atb_cdr_pbias', 'atb_cdr_pbias', V, w=8, l=2)
    c.p('atb_cdr_pbias', 'cdr_en', V, w=2)                   # bias gate to VDD when off
    # IB_PLL: 10 uA PMOS copy of the reference; off and clamped to VSS when disabled or in hold
    c.p('ibs', 'atb_cdr_pbias', V, w=8, l=2)
    c.p('IB_PLL', 'ibclamp', 'ibs', w=4)
    c.n('IB_PLL', 'ibclamp', 'VSS', w=4)
    # Bang-bang pump, current steering (extracted lesson: a switch in series with a long-channel source
    # starves it -- the stack's channel charge (~0.2 pC) must be rebuilt by its own 50 nA, so a word-long
    # pulse delivered ~nothing; a plain drain-side switch dumps fC per toggle, more than the 0.4 fC a
    # decision is worth).  The sources run continuously and NMOS switches steer each current either onto
    # VCTRL or onto VDUMP, which a unity-gain OTA (~0.6 uA, on whenever cdr_en) holds at VCTRL, so the
    # source drains never change voltage.
    #   OTA: NMOS pair (VCTRL +, VDUMP -), PMOS mirror, output VDUMP
    c.n('ota_t', 'nbd', 'ota_e', w=.5, l=4)
    c.n('ota_e', 'cdr_en', 'VSS', w=1)
    c.n('ota_1', 'VCTRL', 'ota_t', w=2, l=1)
    c.n('VDUMP', 'VDUMP', 'ota_t', w=2, l=1)
    c.p('ota_1', 'ota_1', V, w=1, l=2)
    c.p('VDUMP', 'ota_1', V, w=1, l=2)
    #   steering controls (bbon = cdr_en & freq_hold)
    c.nand(['BB_UP', 'bbon'], 'up_n', wn=1, wp=2)
    c.inv('up_n', 'up_on', wn=1, wp=2)
    c.nand(['BB_DN', 'bbon'], 'dn_n', wn=1, wp=2)
    c.inv('dn_n', 'dn_on', wn=1, wp=2)
    c.nand(['up_on', 'bb_gain'], 'up2_n', wn=1, wp=2)
    c.inv('up2_n', 'up2_on', wn=1, wp=2)
    c.nand(['dn_on', 'bb_gain'], 'dn2_n', wn=1, wp=2)
    c.inv('dn2_n', 'dn2_on', wn=1, wp=2)
    for k, (src_on, src_off, kind) in enumerate((('up_on', 'up_n', 'p'), ('up2_on', 'up2_n', 'p'),
                                                 ('dn_on', 'dn_n', 'n'), ('dn2_on', 'dn2_n', 'n'))):
        node = f'bbs{k}'
        if kind == 'p':
            _long_stack(c, 'p', node, 'atb_cdr_pbias', V, 1, 10, 4, b=V)
        else:
            _long_stack(c, 'n', node, 'nbd', 'VSS', .5, 10, 4)
        c.n('VCTRL', src_on, node, w=.5)       # steer to the loop filter
        c.n('VDUMP', src_off, node, w=.5)      # ... or to the follower
    return c


BLOCKS = dict(termination=termination, rxlevel=rxlevel, rxselect=rxselect, wmon_sel=wmon_sel,
              ctle=ctle, slicer=slicer, detect=detect, cdr=cdr)


def write_all():
    for name, fn in BLOCKS.items():
        c = fn()
        nets = set(c.ports)
        for line in c.lines:
            if line.startswith('X'):
                nets.update(t for t in line.split()[1:] if '=' not in t)
        low = {}
        for n in nets:      # SPICE is case-insensitive, Magic/Netgen are not
            if n.lower() in low and low[n.lower()] != n:
                raise ValueError(f'{name}: nets {n} and {low[n.lower()]} differ only in case')
            low[n.lower()] = n
        (HERE / f'{name}.spice').write_text(c.emit())


if __name__ == '__main__':
    write_all()
    for name in BLOCKS:
        txt = (HERE / f'{name}.spice').read_text()
        print(name, sum(1 for l in txt.splitlines() if l.startswith('X')), 'instances')
