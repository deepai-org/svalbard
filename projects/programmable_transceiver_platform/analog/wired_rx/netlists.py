    c.p('ota1', 'AVP', 'ot', w=8, l=2)
    c.p('ota2', 'AVN', 'ot', w=8, l=2)
    # r13 (2026-11-13, AP4-1 repack): output mirror devices 0.5/2 -> 1/4 (same W/L, 4x gate area).  r11/r12 extracted
    # failed the VCTRL compliance criterion at ff/22/3.35 (|dI/I| 0.159 vs 0.15 over 0.8..2.2 V: output conductance of
