"""Transistor-level schematic generator for the wired-receive family.

Writes analog/wired_rx/<block>.spice (gf180mcuD devices only, top subckt
pt_<block>).  The emitted .spice files are the schematic of record used for
LVS and simulation; edit this generator, not the .spice files.

Conventions
  * 3.3 V devices (nfet_03v3 / pfet_03v3) only; NMOS bodies at VSS.
  * Logic: NMOS 1/0.28, PMOS 2/0.28 unless noted.
  * Every block has an active-high enable; with enable low (reset value) or
    with the island rail off, no bias current flows and outputs sit at VSS.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent


class Net:
    def __init__(self, name, ports, doc):
        self.name, self.ports, self.doc = name, ports, doc
        self.lines = []
        self.count = {}
        # StrongARM sizing knobs (slicer overrides for speed)
        self.sa_k, self.sa_rst, self.sa_latch, self.sa_buf = 1, 1, 1, False

    def _id(self, prefix):
        self.count[prefix] = self.count.get(prefix, 0) + 1
        return f'{prefix}{self.count[prefix]}'

    def n(self, d, g, s, w=1., l=.28, m=1, name=None):
        self.lines.append(f'X{name or self._id("MN")} {d} {g} {s} VSS nfet_03v3 w={w:g}u l={l:g}u'
                          + (f' m={m}' if m > 1 else ''))

    def p(self, d, g, s, b=None, w=2., l=.28, m=1, name=None):
        self.lines.append(f'X{name or self._id("MP")} {d} {g} {s} {b or self.vdd} pfet_03v3 w={w:g}u l={l:g}u'
                          + (f' m={m}' if m > 1 else ''))

    def r(self, a, b, w, l, name=None, seg=6.5):
        k = max(1, -(-l // seg))
        k = int(k)
        prev = a
        for i in range(k):
            nxt = b if i == k - 1 else f'{a}_{b}_r{i}'
            self.lines.append(f'X{(name or self._id("R")) if i == 0 else self._id("R")} {prev} {nxt} VSS ppolyf_u_1k '
                              f'r_width={w:g}u r_length={round(l / k, 3):g}u')
            prev = nxt

    def ncap(self, node, w, l, m=1):
        """NMOS capacitor: gate on `node`, source/drain/body at VSS."""
        self.n('VSS', node, 'VSS', w=w, l=l, m=m, name=self._id('MC'))

    def pcap(self, node, w, l, m=1):
        """PMOS capacitor to the rail: gate on `node`, source/drain/body at VDD."""
        self.p(self.vdd, node, self.vdd, w=w, l=l, m=m, name=self._id('MCP'))

    # ---- logic
    def inv(self, a, y, wn=1., wp=2., l=.28, m=1):
        self.n(y, a, 'VSS', wn, l, m)
        self.p(y, a, self.vdd, w=wp, l=l, m=m)

    def inv_r(self, a, y, vdd, vss, wn=1., wp=2., l=.28):
        self.n(y, a, vss, wn, l)
        self.p(y, a, vdd, b=self.vdd, w=wp, l=l)

    def nand(self, ins, y, wn=1., wp=2.):
        k = len(ins)
        prev = 'VSS'
        for i, a in enumerate(ins):
            nxt = y if i == k - 1 else f'{y}_s{i}'
            self.n(nxt, a, prev, wn * k)
            prev = nxt
        for a in ins:
            self.p(y, a, self.vdd, w=wp)

    def nor(self, ins, y, wn=1., wp=2.):
        k = len(ins)
        prev = self.vdd
        for i, a in enumerate(ins):
            nxt = y if i == k - 1 else f'{y}_s{i}'
            self.p(nxt, a, prev, w=wp * k)
            prev = nxt
        for a in ins:
            self.n(y, a, 'VSS', wn)

    def tinv(self, a, y, en, enb, wn=1., wp=2., vdd=None, vss='VSS'):
        """Tri-state inverter: drives y=!a when en=1."""
        # enable devices at the rails: a disabled cell draws no supply current
        # even while its input toggles
        u = self._id(f'{y}_t')
        self.p(f'{u}p', enb, vdd or self.vdd, w=wp)
        self.p(y, a, f'{u}p', w=wp)
        self.n(y, a, f'{u}n', wn)
        self.n(f'{u}n', en, vss, wn)

    def tg(self, a, b, en, enb, wn=2., wp=4., m=1):
        self.n(a, en, b, wn, m=m)
        self.p(a, enb, b, w=wp, m=m)

    def rowbreak(self):
        self.lines.append('* ROWBREAK')

    def emit(self):
        head = [f'* {self.name}: generated by analog/wired_rx/netlists.py -- do not edit by hand',
                *[f'* {line}' for line in self.doc.strip().splitlines()],
                f'.subckt {self.name} ' + ' '.join(self.ports)]
        return '\n'.join(head + self.lines + [f'.ends {self.name}', ''])


