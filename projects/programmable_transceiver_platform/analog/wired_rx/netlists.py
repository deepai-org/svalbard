def _strongarm(c, tag, ck, inp, inn, outp_name, ref=None, trim=None, ckn_ext=None, tail_src=None):
    """PMOS-input StrongARM + NOR SR latch.  Evaluates while `ck` is high.

    outp_name goes high when inp < inn ... (polarity fixed below so that
    outp_name = 1 when v(inp) > v(inn)).  `ref`=(refp, refn) adds a second pair
    so the decision is (inp-inn) > (refp-refn).  `trim`: (tp0,tp1,tn0,tn1) bits.
    """
    V = c.vdd
    c.rowbreak()
    if ckn_ext is None:
        ckn = f'{tag}_ckn'
        c.nand([ck, c.en], ckn, wn=c.sa_k * 4, wp=c.sa_k * 8)
    else:
        # half-rate: the complementary clock is the tail/reset drive directly (no local
        # inversion delay); enable gating is the shared tail header `tail_src`
        ckn = ckn_ext
    # names sort as 1pa < 2oa < 3ob < 4pb so routing-track neighbours are symmetric
    x, pa, pb, oa, ob = (f'{tag}_{s}' for s in ('x', '1pa', '4pb', '2oa', '3ob'))
    c.p(x, ckn, tail_src or V, w=c.sa_k * 16)
    # Higher gate voltage -> less current.  inp on side a: if inp > inn, side b
    # integrates faster and ob rises first.
    c.p(pa, inp, x, w=c.sa_k * 12)
    c.p(pb, inn, x, w=c.sa_k * 12)
    if ref is not None:
        refp, refn = ref
        # side a also sees refn, side b sees refp: decision (inp-inn) vs (refp-refn)
        c.p(pa, refn, x, w=c.sa_k * 12)
        c.p(pb, refp, x, w=c.sa_k * 12)
    c.p(oa, ob, pa, w=c.sa_k * 8)
    c.p(ob, oa, pb, w=c.sa_k * 8)
    c.n(oa, ob, 'VSS', w=c.sa_k * 4)
    c.n(ob, oa, 'VSS', w=c.sa_k * 4)
    for node in (pa, pb, oa, ob):
        c.n(node, ckn, 'VSS', w=c.sa_rst)
    if trim is not None:
        tp0, tp1, tn0, tn1 = trim
        for node, b0, b1 in ((pa, tp0, tp1), (pb, tn0, tn1)):
            # switch-only trim: the switch connects its floating diffusion (~1-2 fF)
            # to the integrating node; a MOS-cap unit (~7 fF) moved the offset > 250 mV
            c.n(f'{tag}_9{node[-2:]}t0', b0, node, w=.5)
            c.n(f'{tag}_9{node[-2:]}t1', b1, node, w=1.)
    # NOR SR latch: ob high (inp>inn) sets q
    q, qb = f'{tag}_q', f'{tag}_qb'
    c.nor([oa, qb], q, wn=c.sa_latch, wp=2 * c.sa_latch)
    c.nor([ob, q], qb, wn=c.sa_latch, wp=2 * c.sa_latch)
    # gated output: out = q & en = NOR(qb, enb)
    if c.sa_buf:
        c.nor([qb, c.enb], f'{tag}_o1', wn=2, wp=4)
        c.inv(f'{tag}_o1', f'{tag}_o2', wn=2, wp=4)
        c.inv(f'{tag}_o2', outp_name, wn=4, wp=8)
    else:
        c.nor([qb, c.enb], outp_name, wn=2, wp=4)
    c.rowbreak()


def _ms_flop(c, tag, d, clk, clkb, vdd, vss):
    """Static transmission-gate master-slave flop, captures d on clk rising (clkb = !clk).
    Returns (s, sb) where sb = captured d and s = !d (both static).  Strong TGs/inverters with
    weak (0.5 um) keepers so the internal nodes swing fully at a 1.25 GHz clock."""
    m, mb, sl, sb = (f'{tag}_{x}' for x in ('m', 'mb', 's', 'sb'))
    c.tg(d, m, clkb, clk, wn=4, wp=8)                      # master transparent while clk low
    c.inv_r(m, mb, vdd, vss, wn=6, wp=12)
    c.tinv(mb, m, clk, clkb, wn=.5, wp=.5, vdd=vdd, vss=vss)  # weak master keeper (clk high)
    c.tg(mb, sl, clk, clkb, wn=6, wp=12)                   # slave transparent while clk high
    c.inv_r(sl, sb, vdd, vss, wn=4, wp=8)
    c.tinv(sb, sl, clkb, clk, wn=.5, wp=.5, vdd=vdd, vss=vss)  # weak slave keeper (clk low)
    return sl, sb


