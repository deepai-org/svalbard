#!/usr/bin/env python3
"""Register addresses for tb_top_boundary.sv of one chip, from spec/register-map.json (so the bench cannot go stale).
    gen_defs.py <rf|wired> [register-map.json]
The bench drives one probe block per chip: the LNA on pt_rf (lna.match.ctrim -> ct0..3, lna.state), the CTLE on pt_wired
(ctle.config.peak -> ctle_peak0..2, ctle.state)."""
import json, os, sys
P = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
chip = sys.argv[1]
f = {x['name']: x for x in json.load(open(sys.argv[2] if len(sys.argv) > 2 else os.path.join(P, 'spec/register-map.json')))['fields']}
def addr(n): return f[n]['chunks'][0]['addr']
def lsb(n): return f[n]['chunks'][0]['reg_lsb']
trim, state = {'rf': ('lna.match.ctrim', 'lna.state.state'), 'wired': ('ctle.config.peak', 'ctle.state.state')}[chip]
print(f'// GENERATED by sim/gen_defs.py {chip} from spec/register-map.json')
print(f"`define PT_REG_PROBE_TRIM_ADDR 8'd{addr(trim)}")
assert lsb(trim) == 0 and lsb(state) == 0
print(f"`define PT_REG_PROBE_TRIM_RESET {f[trim]['bits']}'d{f[trim]['default']}")
print(f"`define PT_REG_PROBE_STATE_ADDR 8'd{addr(state)}")
print(f"`define PT_REG_UNRELATED_ADDR 8'd{addr('debug.calibration.tag')}")      # a field with no analog pin (both chips)
print(f"`define PT_REG_AOSC_ADDR 8'd{addr('core.aosc.enable')}")
print(f"`define PT_REG_AOSC_RESET 1'b{f['core.aosc.enable']['default'] or 0}")
assert lsb('core.aosc.enable') == 0
a = f['debug.atb.atb1']; assert a['chunks'][0]['addr'] == 0x4A
print(f"`define PT_REG_ATB1_CODE5 16'd{5 << a['chunks'][0]['reg_lsb']}")
