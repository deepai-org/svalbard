#!/usr/bin/env python3
"""Write integration/pt_chip.sv from the one chip-level connectivity integration/top/pt_chip.conn (TOP-2).
pt_chip = pt_host_physical (provider host pads) + pt_debug_physical (observation pads) + pad_strap (POR_BYPASS)
+ pt_digital_macro + pt_analog_top (black box generated by integration/top/check_top.py --write).
Only the chip-level instances of the conn are read here (digital, host, debug_pads, pad_por_bypass); everything
else is inside pt_analog_top, whose port names are the conn net names.
    python3 integration/gen_pt_chip.py          # write
    python3 integration/gen_pt_chip.py --check  # fail if integration/pt_chip.sv is stale"""
import os, re, sys, collections
HERE = os.path.dirname(os.path.abspath(__file__)); P = os.path.dirname(HERE)
sys.path.insert(0, HERE + '/top')
import check_top as ct

def bus(n):
    m = re.fullmatch(r'(\w+)\[(\d+)\]', n)
    return (m.group(1), int(m.group(2))) if m else (n, None)

def main():
    conn = open(HERE + '/top/pt_chip.conn').read()
    inst, ports, _, err = ct.parse(conn)
    assert not err, err
    rtl = ct.rtl_macro_ports(open(P + '/rtl/pt_digital_macro.sv').read())          # name -> (dir, width)
    top = open(HERE + '/top/generated/pt_analog_top.sv').read()
    atop = [(d, int(w or 0) + 1, n) for d, w, n in re.findall(r'^\s*(input|output|inout) wire (?:\[(\d+):0\] )?(\w+)', top, re.M)]
    ctl = [(c[0].strip(), int(c[1])) for c in (l.split('|') for l in open(HERE + '/top/ctl_ports.txt') if l.startswith('c_'))]
    width = collections.defaultdict(int)                    # net base -> width (0 = scalar)
    def note(net):
        b, i = bus(net)
        if b in ('VDD', 'VSS', '-'): return
        width[b] = max(width[b], 0 if i is None else i + 1)
    for name in ('digital', 'host', 'debug_pads', 'pad_por_bypass'):
        for _, (_, net) in inst[name]['pins'].items(): note(net)
    for _, w, n in atop:
        if n not in ('VDD', 'VSS'): width[n] = max(width[n], w if w > 1 else 0)
    for n, w in ctl: width[n] = w if w > 1 else 0
    cports = collections.OrderedDict()
    for p in sorted(ports, key=lambda x: (bus(x)[0], bus(x)[1] or 0)):
        b, i = bus(p); cports[b] = max(cports.get(b, 0), 0 if i is None else i + 1)
    L = []; a = L.append
    a('// GENERATED by integration/gen_pt_chip.py from integration/top/pt_chip.conn. Do not edit: edit the conn and regenerate.')
    a('// pt_chip: provider host / observation / strap pads, the hardened digital macro and the analog top (black box')
    a('// generated from the same conn: integration/top/generated/pt_analog_top.sv; structural netlist pt_analog_top.spice).')
    a('// Every analog, island-switch, debug and fallback control reaches the analog top through the macro\'s named,')
    a('// decoded c_* ports (integration/top/ctl_ports.txt). Reset: rtl/pt_por_path.sv inside the macro.')
    a('`include "pt_regmap_defs.svh"')
    a('module pt_chip(')
    a(',\n'.join(f" inout wire{'[%d:0]' % (w - 1) if w else ''} {n}" for n, w in cports.items()) + ');')
    for n, w in sorted(width.items()):
        if n not in cports: a(f" wire{'[%d:0]' % (w - 1) if w else ''} {n};")
    def expr(net): return "1'b1" if net == 'VDD' else "1'b0" if net == 'VSS' else net
    # digital macro: one local vector per port, bit-wise assigns to / from the conn nets
    pins = inst['digital']['pins']; conns = []
    for port, (d, w) in rtl.items():
        if port.startswith('c_'): conns.append(f'.{port}({port})'); continue
        a(f" wire{'[%d:0]' % (w - 1) if w > 1 else ''} m_{port};")
        conns.append(f'.{port}(m_{port})')
        for i in range(w):
            key = port if w == 1 and port in pins else f'{port}[{i}]'
            if key not in pins: raise SystemExit(f'macro pin {key} is not bound in pt_chip.conn')
            net = pins[key][1]; sel = f'm_{port}[{i}]' if w > 1 else f'm_{port}'
            if d == 'input': a(f' assign {sel} = {expr(net)};')
            elif net != '-': a(f' assign {net} = {sel};')
    a(' pt_digital_macro digital(' + ',\n  '.join(', '.join(conns[i:i + 6]) for i in range(0, len(conns), 6)) + ');')
    h = inst['host']['pins']
    a(' // Host pads: provider cells only (integration/pt_provider_io.sv); the logical supply groups are one VDD / VSS here.')
    a(' pt_host_physical host(.RESET_N(RESET_N), .SPI_SCLK(SPI_SCLK), .SPI_CS_N(SPI_CS_N), .SPI_MOSI(SPI_MOSI), .SPI_MISO(SPI_MISO),')
    a('  .H2D(H2D), .H2D_CLK(H2D_CLK), .D2H(D2H), .D2H_CLK(D2H_CLK), .VDD_CORE(VDD), .VSS_CORE(VSS), .VDD_HOST_A(VDD), .VSS_HOST_A(VSS),')
    a('  .VDD_HOST_B(VDD), .VSS_HOST_B(VSS), ' + ', '.join(f'.{p}({h[p][1] if p in h else bus(h[p + "[0]"][1])[0]})' for p in
      ('rst_n', 'sclk', 'cs_n', 'mosi', 'miso', 'miso_oe', 'h2d_clk', 'h2d_pin', 'd2h_pin', 'd2h_clk_pin', 'd2h_oe', 'd2h_pdrv', 'd2h_sl')) + ');')
    dp = inst['debug_pads']['pins']
    a(' pt_debug_physical debug_pads(.VDD_CORE(VDD), .VSS_CORE(VSS), ' + ', '.join(f'.{p}({n})' for p, (_, n) in dp.items() if p not in ('VDD', 'VSS')) + ');')
    sp = inst['pad_por_bypass']['pins']
    a(' // POR_BYPASS strap (DT-10, D-POR): input-only provider pad with a hard-tied pull-down; Y -> macro por_bypass.')
    a(f" pad_strap pad_por_bypass(.PAD({sp['PAD'][1]}), .Y({sp['Y'][1]}), .VDD(VDD), .VSS(VSS));")
    a(' pt_analog_top analog(' + ',\n  '.join(', '.join(f'.{n}({n})' for _, _, n in atop[i:i + 8]) for i in range(0, len(atop), 8)) + ');')
    a('endmodule')
    a('')
    a('// Declarations for interface-only checks. Define PT_EXTERNAL_IO and compile pt_provider_io.sv to bind the provider')
    a('// cells; define PT_EXTERNAL_ANALOG and compile a model (integration/top/generated/pt_analog_top_stub.sv) for the analog top.')
    a('`ifndef PT_EXTERNAL_IO')
    a('(* blackbox *) module pt_host_physical(')
    a(' inout wire RESET_N,SPI_SCLK,SPI_CS_N,SPI_MOSI,output wire SPI_MISO,')
    a(' inout wire[9:0]H2D,inout wire H2D_CLK,output wire[9:0]D2H,output wire D2H_CLK,')
    a(' inout wire VDD_CORE,VSS_CORE,VDD_HOST_A,VSS_HOST_A,VDD_HOST_B,VSS_HOST_B,')
    a(' output wire rst_n,sclk,cs_n,mosi,input wire miso,miso_oe,')
    a(' output wire h2d_clk,output wire[9:0]h2d_pin,input wire[9:0]d2h_pin,input wire d2h_clk_pin,d2h_oe,')
    a(' input wire[1:0]d2h_pdrv,input wire d2h_sl);')
    a('endmodule')
    a('(* blackbox *) module pt_debug_physical(')
    a(' inout wire VDD_CORE,VSS_CORE,output wire CLK_OBS,DBG_OBS0,DBG_OBS1,')
    a(' input wire clk_obs,clk_obs_oe,dbg_obs0,dbg_obs0_oe,dbg_obs1,dbg_obs1_oe);')
    a('endmodule')
    a('(* blackbox *) module pad_strap(inout wire PAD,output wire Y,inout wire VDD,VSS);')
    a('endmodule')
    a('`endif')
    a('`ifndef PT_EXTERNAL_ANALOG')
    a('`include "pt_analog_top.sv"')
    a('`endif')
    text = '\n'.join(L) + '\n'
    out = HERE + '/pt_chip.sv'
    if '--check' in sys.argv:
        if open(out).read() != text: raise SystemExit('integration/pt_chip.sv is stale: run integration/gen_pt_chip.py')
        print('pt_chip.sv is current')
    else:
        open(out, 'w').write(text); print('wrote', out, len(L), 'lines')

if __name__ == '__main__':
    main()
