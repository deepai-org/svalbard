#!/usr/bin/env python3
"""Register addresses for tb_top_boundary.sv, from spec/register-map.json (so the bench cannot go stale)."""
import json, os, sys
P = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
f = {x['name']: x for x in json.load(open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(P, 'spec/register-map.json')))['fields']}
def addr(n): return f[n]['chunks'][0]['addr']
def lsb(n): return f[n]['chunks'][0]['reg_lsb']
print('// GENERATED by sim/gen_defs.py from spec/register-map.json')
print(f"`define PT_REG_LNA_MATCH_ADDR 8'd{addr('lna.match.ctrim')}")
assert lsb('lna.match.ctrim') == 0
print(f"`define PT_REG_LNA_CT_RESET 4'd{f['lna.match.ctrim']['default']}")
print(f"`define PT_REG_LNA_STATE_ADDR 8'd{addr('lna.state.state')}")
assert lsb('lna.state.state') == 0
print(f"`define PT_REG_PATTERN_ADDR 8'd{addr('debug.pattern.user_word')}")
print(f"`define PT_REG_AOSC_ADDR 8'd{addr('core.aosc.enable')}")
assert lsb('core.aosc.enable') == 0
a = f['debug.atb.atb1']; assert a['chunks'][0]['addr'] == 0x4A
print(f"`define PT_REG_ATB1_CODE5 16'd{5 << a['chunks'][0]['reg_lsb']}")
