// H2D capture flop with a kept select in front (en=1 tied for r/f, the fh pair enable for fh):
// every pin-capture path is hio_ib -> hio_m (I1 -> Z) -> D, so all 30 capture flops see one window.
module pt_hio_cap #(parameter NEG=0) (input wire clk,rst_n,en,d,output wire q);
`ifdef SYNTHESIS
 // The FIXED capture flop drives only its own select (hio_q, dont_touch) and a local buffer qb that
 // drives the domain logic: the resizer never sees a long or heavy net on the fixed flop, so it never
 // resizes it (TC13 pA: dffrnq_1 -> _2 resize of a FIRM flop overlapped a tap cell).
 wire hio_md,hio_q;
 gf180mcu_fd_sc_mcu7t5v0__mux2_2 hio_m(.I0(hio_q),.I1(d),.S(en),.Z(hio_md));
 generate if (NEG) begin : n
  gf180mcu_fd_sc_mcu7t5v0__dffnrnq_1 lf(.D(hio_md),.RN(rst_n),.CLKN(clk),.Q(hio_q));
 end else begin : p
  gf180mcu_fd_sc_mcu7t5v0__dffrnq_1 lr(.D(hio_md),.RN(rst_n),.CLK(clk),.Q(hio_q));
 end endgenerate
 (* keep=1 *) gf180mcu_fd_sc_mcu7t5v0__buf_2 qb(.I(hio_q),.Z(q));
`else
 reg r;
 generate if (NEG) begin : n
  always @(negedge clk or negedge rst_n) if(!rst_n) r<=1'b0; else if(en) r<=d;
 end else begin : p
  always @(posedge clk or negedge rst_n) if(!rst_n) r<=1'b0; else if(en) r<=d;
 end endgenerate
 assign q=r;
`endif
endmodule
