// ---------------- Host-link pad-edge I/O block (TC13, coordinator decision 2026-11-11) ----------------
// Hand-instantiated cells with FIXED placement (verification/digital_hardening/config.json
// MACRO_PLACEMENT_CFG, generated by scratch/digital-timing-close/hio/hioplace.py) next to the pins.
// Every net from the launch flops' Q to the D2H pins, and from the H2D pins to the capture flops' D,
// carries the "hio_" name (or is a pin net) and is dont_touch for the resizer (RSZ_DONT_TOUCH_RX), as are
// the hio_* cells: no repair buffer, no resize, no synthesis port buffer on these paths. The launch
// and capture flops themselves are not dont_touch (CTS must connect their clock pins).
//
// D2H lane (10 data lanes and the forwarded clock, identical cells): rising launch flop lr
// (dffrnq_1) and falling launch flop lf (dffnrnq_1), pin = lr ^ lf through hio_x (xor2_1), then
// pt_stagger / pt_out_mux: hio_d0 -> hio_d1 (two buf_1, the HB-1 stagger delay, present on every
// lane including the clock so every xor sees the same load), hio_m (mux2_2), then hio_ob (buf_8) -> pin,
// instantiated in pt_host_link with its Z on the port bit itself (a module port in between aliases a
// 1-bit wire to a bit of the d2h_pin bus and the flow's insbuf pass adds a buf_1 to the data lanes only).
module pt_hio_launch(input wire clk,sel,rst_n,nrst_n,dr,df,output wire z);
// ODDR launch (TC13 r4, coordinator decision): z = sel ? q_f : q_r, sel = the hddr clock through the
// block's dedicated select buffer. q_r changes after the rising edge while q_f is selected and q_f
// after the falling edge while q_r is selected, so every pin edge is the select edge through the mux
// (identical cells, edge and placement on the clock lane and the data lanes), not a flop clk->Q.
`ifdef SYNTHESIS
 wire hio_qr,hio_qf;
 gf180mcu_fd_sc_mcu7t5v0__dffrnq_1 lr(.D(dr),.RN(rst_n),.CLK(clk),.Q(hio_qr));
 gf180mcu_fd_sc_mcu7t5v0__dffnrnq_1 lf(.D(df),.RN(nrst_n),.CLKN(clk),.Q(hio_qf));
 (* keep=1,dont_touch=1 *) gf180mcu_fd_sc_mcu7t5v0__mux2_2 hio_x(.I0(hio_qr),.I1(hio_qf),.S(sel),.Z(z));
`else
 reg qr,qf;
 always @(posedge clk or negedge rst_n) if(!rst_n) qr<=1'b0; else qr<=dr;
 always @(negedge clk or negedge nrst_n) if(!nrst_n) qf<=1'b0; else qf<=df;
 assign z=sel?qf:qr;
`endif
endmodule

// HB-1 D2H launch stagger: a fixed two-stage delay (two kept buf_1, no repair may touch them) and
// a kept select mux. Characterized in-window libraries (buf_1 into buf_1): 0.38 ns/stage ss_032C_3v15,
// 0.19 ns/stage ff_022C_3v35, so the staggered group lags by ~0.4-0.8 ns plus wire (not 1/2 UI).
module pt_stagger(input wire I,S,output wire Z);
`ifdef SYNTHESIS
 wire hio_a,hio_b;
 (* keep=1,dont_touch=1 *) gf180mcu_fd_sc_mcu7t5v0__buf_1 hio_d0(.I(I),.Z(hio_a));
 (* keep=1,dont_touch=1 *) gf180mcu_fd_sc_mcu7t5v0__buf_1 hio_d1(.I(hio_a),.Z(hio_b));
 (* keep=1,dont_touch=1 *) gf180mcu_fd_sc_mcu7t5v0__mux2_2 hio_m(.I0(I),.I1(hio_b),.S(S),.Z(Z));
`else
 assign Z=I;   // zero-delay simulation: the stagger is a physical delay only
`endif
endmodule

