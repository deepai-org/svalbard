#!/usr/bin/env python3
"""Port glue for the gate-level bench sim/tb_digital_gl.sv, from the header of rtl/pt_digital_macro.sv.

The macro has about 300 ports; the bench drives a dozen inputs and logs EVERY output. This script writes
tb_gl_ports.svh with
  * one `wire [range] o_<name>;` per macro output,
  * `PT_GL_OUT_CONN   .name(o_name), ...   (all outputs)
  * `PT_GL_IN_TIE     .name({W{1'b0}}), ... (every input the bench does not drive itself: --driven a,b,c)
  * `PT_GL_NOUT / task gl_dump(fd): one "name=hex" token per output, in port order (the lockstep record)
and prints the port counts. Usage: gls_ports.py --out DIR --driven reset_n_pad,por_n,...
"""
import argparse
import re
from pathlib import Path

P = Path(__file__).resolve().parents[2]


def ports():
    src = (P / 'rtl/pt_digital_macro.sv').read_text()
    hdr = re.sub(r'//[^\n]*', '', src[src.index('module pt_digital_macro('):])
    hdr = hdr[hdr.index('(') + 1:hdr.index(');')]
    out = []
    for decl in re.finditer(r'(input|output)\s+wire\s*(\[[^\]]*\])?\s*([^;]*?)(?=(?:\binput\b|\boutput\b|$))', hdr, re.S):
        d, rng, names = decl.group(1), decl.group(2) or '', decl.group(3)
        for n in names.split(','):
            n = n.strip()
            if n:
                assert re.fullmatch(r'\w+', n), (n, decl.group(0)[:80])
                out.append((d, rng, n))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    ap.add_argument('--driven', default='')
    a = ap.parse_args()
    driven = [x for x in a.driven.split(',') if x]
    pl = ports()
    ins = [p for p in pl if p[0] == 'input']
    outs = [p for p in pl if p[0] == 'output']
    names = {p[2] for p in ins}
    missing = [d for d in driven if d not in names]
    assert not missing, f'driven inputs that are not macro inputs: {missing}'
    L = ['// GENERATED by verification/digital_hardening/gls_ports.py from rtl/pt_digital_macro.sv: do not edit']
    for _, rng, n in outs:
        L.append(f'wire {rng} o_{n};')
    L.append('`define PT_GL_OUT_CONN ' + ', '.join(f'.{n}(o_{n})' for _, _, n in outs))
    def zero(rng):
        if not rng:
            return "1'b0"
        hi, lo = rng[1:-1].split(':')
        return f"{{(({hi})-({lo})+1){{1'b0}}}}"
    tie = [f'.{n}({zero(rng)})' for _, rng, n in ins if n not in driven]
    L.append('`define PT_GL_IN_TIE ' + ', '.join(tie))
    L.append(f'`define PT_GL_NOUT {len(outs)}')
    L.append('task gl_dump(input integer fd); begin')
    for _, _, n in outs:
        L.append(f'  $fwrite(fd, " {n}=%h", o_{n});')
    L.append('end endtask')
    Path(a.out).mkdir(parents=True, exist_ok=True)
    (Path(a.out) / 'tb_gl_ports.svh').write_text('\n'.join(L) + '\n')
    print(f'{len(ins)} inputs ({len(driven)} driven by the bench, {len(tie)} tied 0), {len(outs)} outputs')


if __name__ == '__main__':
    main()
